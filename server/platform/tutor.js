// ─────────────────────────────────────────────────────────────────────────────
// Pri Learning · /v1/tutor
//
// Grounded, three-level help for a practice question: a nudge, then a Socratic
// question, then a narrated walkthrough of the verified solution — and, once
// the ladder has started, a conversation: the student types a question in
// their own words and the tutor answers under the same rules. The words may
// come from a model; the mathematics never does, and nothing here marks.
//
// What this route guarantees, in the order the handler enforces it:
//
//   1. Signed in, email verified, guardian consent (mounted in router.js), and
//      a per-account hourly limit.
//   2. Practice only. A body that does not say `context: "practice"` is
//      refused, and one that says "exam" is refused with TUTOR_EXAM_LOCKED.
//      The local backend refuses earlier still (assertPracticeRow), so an exam
//      question never reaches this server; this is the second wall, not the
//      only one.
//   3. A closed, size-bounded body. No names, emails or profile ids: the only
//      student data sent on is the work lines and typed answer.
//   4. Cache before spend. An identical request in the last 24 hours is
//      answered from tutor_cache without a model call.
//   5. One unit of the deployment-wide paid-call ceiling per model call.
//   6. A per-account daily allowance (PRI_TUTOR_CALLS_PER_ACCOUNT_DAY, higher
//      for premium via PRI_TUTOR_CALLS_PER_ACCOUNT_DAY_PREMIUM), so one account
//      cannot drain the shared ceiling, and maths-only content limits, so the
//      route cannot be used as a general model proxy.
//   7. The reply is checked against the verified solution (tutorGuard.js). A
//      leaked answer is regenerated once; a second leak falls back to the
//      question's own authored hint, or a generic deterministic nudge. Captions
//      may only reword: their maths must be verbatim spans of the verified step.
//
//   8. A conversational turn (level "ask") carries the student's typed question
//      (≤600 chars, control characters stripped, framed to the model as data)
//      and the last six turns of the exchange, trimmed here whatever the client
//      sent. Its cache key is scoped to the account: a free-text exchange is
//      never read back by another account. The fixed-ladder levels keep the
//      content-keyed shared cache, because their requests carry no free text.
//  10. A diagnosis (level "diagnose") explains work the deterministic engine
//      has ALREADY judged: what was right, the first place it went wrong and
//      why, and the single next step. The engine's verdict is the input, never
//      the output — nothing in the reply is a mark, and the mark does not move.
//      One model call (one unit of the ceiling, one of the daily allowance); its
//      mathematics must be copied from the verified solution, the question or
//      the student's own lines (diagnosisGroundingIssues), and while the attempt
//      is open the answer guard runs on every part as well. A reply that fails
//      either check, or no model at all, gives the deterministic diagnosis built
//      from the engine's first break and the solution's next step.
//
//   9. POST /stream answers an ask/nudge/socratic turn as server-sent events.
//      Every refusal above still happens first, as JSON, before a byte of the
//      stream; the model's text is released one guarded sentence at a time
//      (tutorGuard.createReleaseGate), a leak ends the stream with the authored
//      hint (`event: fallback`) and is never cached, and one session may hold
//      one open stream — a newer one closes the older.
//
// What it cannot see: whether the question is in an active exam. The client
// tells it (`context`), and the local backend refuses exam rows before calling;
// a modified client could misreport. The daily allowance bounds that misuse,
// and the replies never contain the answer whatever the context.
//
// Two groundings. A SERVER-ISSUED practice question (/v1/practice/issue) is
// grounded here, from the server's own escrowed question: the body names it
// (`serverQuestionId`) and carries no prompt, step or answer — the device does
// not hold them and its word for them would not be taken. The escrow is read
// for the signed-in account only, so another account's question id is a 404,
// and until that question is resolved the guard never excuses the answer, the
// walkthrough level is refused, and no reply field carries the solution.
//
// A DEVICE question (generated by the bundled engine, no server id) keeps the
// older contract, where the server cannot verify the solution it is grounded
// in: the "verified" steps and answer are the client's word. What bounds that: the body is
// closed and size-limited, the guard protects the client's own stated answer
// and step results so a forged solution cannot extract a real one, a reply
// may never echo a step verbatim, and the cache key covers the solution's
// content so one client's forgery is never served to another.
// ─────────────────────────────────────────────────────────────────────────────
