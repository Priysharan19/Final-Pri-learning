// ─────────────────────────────────────────────────────────────────────────────
// Pri Learning · object storage for hosted library files (ADR-0002 plan F3)
//
// One small interface — put, get, head, delete, signedReadUrl — and two
// adapters:
//
//   · local   a directory on disk, for development and tests only. Refused in
//             production (NODE_ENV=production): it has no region and no
//             separate failure domain.
//   · s3      any S3-compatible object store, configured only by server
//             variables, signed with AWS Signature Version 4 (no SDK).
//
// OFF UNLESS CONFIGURED. With no PRI_RESOURCE_STORAGE the factory returns null
// and a 'hosted' resource stays refused, exactly as before F3.
//
// REGION RULE. Every edition has a data-residency region (ADR-0002 §5: IN →
// India, AU → Australia). The adapter REFUSES TO START when its configured
// region is not one of the edition's: a Prithagoras deployment cannot be
// pointed at an Indian bucket, nor the reverse. There is no Australian bucket
// yet, so hosted files cannot be enabled for Prithagoras until O1.
//
// Keys are generated by the server (`resources/<resourceId>/<revision>.pdf`);
// no caller-supplied name ever reaches a storage path. A storage key never
// leaves the server: students get a short-lived signed URL.
// ─────────────────────────────────────────────────────────────────────────────
import { createHash, createHmac, timingSafeEqual } from 'node:crypto';
import { mkdir, readFile, writeFile, rm, stat } from 'node:fs/promises';
import { isAbsolute, join, resolve, sep } from 'node:path';

/** The regions each edition's files may live in (server variables name the exact one). */
export const EDITION_STORAGE_REGIONS = Object.freeze({
  priyabhata: Object.freeze(['ap-south-1', 'ap-south-2']),
  prithagoras: Object.freeze(['ap-southeast-2', 'ap-southeast-4'])
});
export const SIGNED_URL_SECONDS = 300;
const KEY = /^(resources|staging)\/[a-z0-9][a-z0-9-]{2,119}\/[0-9]{1,6}(\.pdf|\/[0-9]{1,3})$/;

export function assertKey(key) {
  if (typeof key !== 'string' || !KEY.test(key) || key.includes('..')) throw Object.assign(new Error('Unsafe storage key.'), { code: 'STORAGE_KEY_INVALID' });
  return key;
}
export const assetKey = (resourceId, revision) => assertKey(`resources/${resourceId}/${revision}.pdf`);
export const partKey = (resourceId, revision, index) => assertKey(`staging/${resourceId}/${revision}/${index}`);

const sha256hex = data => createHash('sha256').update(data).digest('hex');
const hmac = (key, data) => createHmac('sha256', key).update(data).digest();
const encode = s => encodeURIComponent(s).replace(/[!'()*]/g, c => `%${c.charCodeAt(0).toString(16).toUpperCase()}`);
const encodePath = p => p.split('/').map(encode).join('/');

function amzDates(now) {
  const iso = new Date(now).toISOString().replace(/[-:]/g, '').replace(/\.\d{3}Z$/, 'Z');
  return { amzDate: iso, day: iso.slice(0, 8) };
}
function signingKey(secret, day, region) {
  return hmac(hmac(hmac(hmac(`AWS4${secret}`, day), region), 's3'), 'aws4_request');
}

/**
 * A presigned GET URL (query-string SigV4). Exported so the test can hold it to
 * AWS's published example. `host` and `path` are the request's, already final.
 */
export function presignGetUrl({ host, path, region, accessKeyId, secretAccessKey, now, expires = SIGNED_URL_SECONDS, protocol = 'https', extraQuery = {} }) {
  const { amzDate, day } = amzDates(now);
  const scope = `${day}/${region}/s3/aws4_request`;
  const query = {
    'X-Amz-Algorithm': 'AWS4-HMAC-SHA256',
    'X-Amz-Credential': `${accessKeyId}/${scope}`,
    'X-Amz-Date': amzDate,
    'X-Amz-Expires': String(expires),
    'X-Amz-SignedHeaders': 'host',
    ...extraQuery
  };
  const canonicalQuery = Object.keys(query).sort().map(k => `${encode(k)}=${encode(query[k])}`).join('&');
  const canonicalRequest = ['GET', encodePath(path), canonicalQuery, `host:${host}\n`, 'host', 'UNSIGNED-PAYLOAD'].join('\n');
  const toSign = ['AWS4-HMAC-SHA256', amzDate, scope, sha256hex(canonicalRequest)].join('\n');
  const signature = createHmac('sha256', signingKey(secretAccessKey, day, region)).update(toSign).digest('hex');
  return `${protocol}://${host}${encodePath(path)}?${canonicalQuery}&X-Amz-Signature=${signature}`;
}

/** Header-signed request (PUT, HEAD, DELETE, GET), returning the headers to send. */
export function signRequest({ method, host, path, region, accessKeyId, secretAccessKey, now, body = Buffer.alloc(0), extra = {} }) {
  const { amzDate, day } = amzDates(now);
  const payload = sha256hex(body);
  const headers = { host, 'x-amz-content-sha256': payload, 'x-amz-date': amzDate, ...extra };
  const names = Object.keys(headers).map(h => h.toLowerCase()).sort();
  const canonicalHeaders = names.map(n => `${n}:${String(headers[Object.keys(headers).find(h => h.toLowerCase() === n)]).trim()}\n`).join('');
  const signedHeaders = names.join(';');
  const canonicalRequest = [method, encodePath(path), '', canonicalHeaders, signedHeaders, payload].join('\n');
  const scope = `${day}/${region}/s3/aws4_request`;
  const toSign = ['AWS4-HMAC-SHA256', amzDate, scope, sha256hex(canonicalRequest)].join('\n');
  const signature = createHmac('sha256', signingKey(secretAccessKey, day, region)).update(toSign).digest('hex');
  return { ...headers, authorization: `AWS4-HMAC-SHA256 Credential=${accessKeyId}/${scope}, SignedHeaders=${signedHeaders}, Signature=${signature}` };
}

/** Local-disk adapter: development and tests. Never production. */
export function createLocalStorage({ dir, now = Date.now, secret = 'local-dev-storage' }) {
  if (!dir || !isAbsolute(dir)) throw Object.assign(new Error('Local resource storage needs an absolute directory.'), { code: 'STORAGE_CONFIG' });
  const root = resolve(dir);
  const file = key => {
    const full = resolve(join(root, assertKey(key)));
    if (!full.startsWith(root + sep)) throw Object.assign(new Error('Unsafe storage key.'), { code: 'STORAGE_KEY_INVALID' });
    return full;
  };
  return {
    kind: 'local', region: 'local',
    async put(key, bytes) { const f = file(key); await mkdir(resolve(f, '..'), { recursive: true }); await writeFile(f, bytes); },
    async get(key) { try { return await readFile(file(key)); } catch { return null; } },
    async head(key) { try { return { byteLength: (await stat(file(key))).size }; } catch { return null; } },
    async delete(key) { await rm(file(key), { force: true }); },
    // A local URL is a token the test can verify; nothing serves it.
    signedReadUrl(key, { seconds = SIGNED_URL_SECONDS } = {}) {
      const expires = Math.floor(now() / 1000) + seconds;
      const sig = createHmac('sha256', secret).update(`${key}\n${expires}`).digest('hex');
      return { url: `file-storage://local/${encodeURI(key)}?expires=${expires}&sig=${sig}`, expiresAt: expires * 1000 };
    },
    verifyLocalUrl(url) {
      const m = /^file-storage:\/\/local\/(.+)\?expires=(\d+)&sig=([0-9a-f]{64})$/.exec(url);
      if (!m) return false;
      const key = decodeURI(m[1]);
      const want = createHmac('sha256', secret).update(`${key}\n${m[2]}`).digest();
      return timingSafeEqual(want, Buffer.from(m[3], 'hex')) && Number(m[2]) * 1000 > now();
    }
  };
}

/** S3-compatible adapter. `fetchImpl` is injectable for tests. */
export function createS3Storage({ endpoint, bucket, region, accessKeyId, secretAccessKey, now = Date.now, fetchImpl = fetch }) {
  const base = new URL(endpoint);
  // Path style on a custom endpoint, virtual-hosted on AWS's own.
  const virtual = /(^|\.)amazonaws\.com$/.test(base.hostname);
  const host = virtual ? `${bucket}.${base.host}` : base.host;
  const pathFor = key => (virtual ? `/${key}` : `/${bucket}/${key}`);
  const send = async (method, key, body) => {
    const path = pathFor(assertKey(key));
    const headers = signRequest({ method, host, path, region, accessKeyId, secretAccessKey, now: now(), body: body || Buffer.alloc(0) });
    const { host: _h, ...sendable } = headers;
    return fetchImpl(`${virtual ? 'https' : base.protocol.replace(':', '')}://${host}${encodePath(path)}`, { method, headers: sendable, body: body && body.length ? body : undefined });
  };
  return {
    kind: 's3', region,
    async put(key, bytes) { const r = await send('PUT', key, bytes); if (!r.ok) throw Object.assign(new Error('Storage write failed.'), { code: 'STORAGE_WRITE_FAILED', status: r.status }); },
    async get(key) { const r = await send('GET', key); return r.ok ? Buffer.from(await r.arrayBuffer()) : null; },
    async head(key) { const r = await send('HEAD', key); return r.ok ? { byteLength: Number(r.headers.get('content-length')) } : null; },
    async delete(key) { const r = await send('DELETE', key); if (!r.ok && r.status !== 404) throw Object.assign(new Error('Storage delete failed.'), { code: 'STORAGE_DELETE_FAILED', status: r.status }); },
    signedReadUrl(key, { seconds = SIGNED_URL_SECONDS } = {}) {
      // Saved, never shown inline: the response is forced to a PDF attachment.
      const url = presignGetUrl({ host, path: pathFor(assertKey(key)), region, accessKeyId, secretAccessKey, now: now(), expires: seconds,
        extraQuery: { 'response-content-disposition': 'attachment', 'response-content-type': 'application/pdf' }, protocol: virtual ? 'https' : base.protocol.replace(':', '') });
      return { url, expiresAt: now() + seconds * 1000 };
    }
  };
}

/** What is wrong with the storage variables for this edition; empty when fine or unconfigured. */
export function storageConfigProblems(env = process.env, edition = 'priyabhata') {
  const kind = String(env.PRI_RESOURCE_STORAGE || '').trim();
  if (!kind) return [];
  const problems = [];
  const production = env.NODE_ENV === 'production';
  if (kind === 'local') {
    if (production) problems.push('PRI_RESOURCE_STORAGE=local is for development and tests only');
    if (!isAbsolute(String(env.PRI_RESOURCE_STORAGE_DIR || ''))) problems.push('PRI_RESOURCE_STORAGE_DIR must be an absolute directory');
  } else if (kind === 's3') {
    for (const name of ['PRI_RESOURCE_STORAGE_ENDPOINT', 'PRI_RESOURCE_STORAGE_BUCKET', 'PRI_RESOURCE_STORAGE_REGION', 'PRI_RESOURCE_STORAGE_ACCESS_KEY_ID', 'PRI_RESOURCE_STORAGE_SECRET_ACCESS_KEY']) {
      if (!String(env[name] || '').trim()) problems.push(`${name} is required`);
    }
    let url = null;
    try { url = new URL(String(env.PRI_RESOURCE_STORAGE_ENDPOINT || '')); } catch { /* reported below */ }
    if (String(env.PRI_RESOURCE_STORAGE_ENDPOINT || '').trim() && (!url || url.protocol !== 'https:')) problems.push('PRI_RESOURCE_STORAGE_ENDPOINT must be an https URL');
    const allowed = EDITION_STORAGE_REGIONS[edition] || [];
    const region = String(env.PRI_RESOURCE_STORAGE_REGION || '').trim();
    if (region && !allowed.includes(region)) problems.push(`PRI_RESOURCE_STORAGE_REGION ${region} is not a region for the ${edition} edition (${allowed.join(', ')})`);
  } else problems.push('PRI_RESOURCE_STORAGE must be local or s3');
  return problems;
}

/** The adapter the environment configures for this edition, or null. Throws on a bad configuration. */
export function createObjectStorage(env = process.env, edition = 'priyabhata', options = {}) {
  const kind = String(env.PRI_RESOURCE_STORAGE || '').trim();
  if (!kind) return null;
  const problems = storageConfigProblems(env, edition);
  if (problems.length) throw Object.assign(new Error(`Resource storage is misconfigured: ${problems.join('; ')}`), { code: 'STORAGE_CONFIG' });
  if (kind === 'local') return createLocalStorage({ dir: env.PRI_RESOURCE_STORAGE_DIR, ...options });
  return createS3Storage({
    endpoint: env.PRI_RESOURCE_STORAGE_ENDPOINT, bucket: env.PRI_RESOURCE_STORAGE_BUCKET, region: env.PRI_RESOURCE_STORAGE_REGION,
    accessKeyId: env.PRI_RESOURCE_STORAGE_ACCESS_KEY_ID, secretAccessKey: env.PRI_RESOURCE_STORAGE_SECRET_ACCESS_KEY, ...options
  });
}
