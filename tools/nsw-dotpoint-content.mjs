#!/usr/bin/env node
// The content review behind "this dot point's questions are on that dot point" (launch QA 26 Nov 2026, review of #1122).
//
// A generator cell (a topic at a level) names its dot points in a registry table, and that table cannot know which dot point a branch of
// the generator really asks about (y9-surface-solids.2, "cone", was answered with cylinders, pyramids and spheres). So a generated question
// is never trusted to be on a dot point because the table says so. For Years 11 and 12 (the product's scope) every issued cell whose dot
// points come from the table was SAMPLED (40 questions, fixed seeds) and every distinct question shape in the sample was READ against the
// topic's dot point titles. tools/nsw-dotpoint-content-review.json holds what was found for each cell:
//   pure   every shape in the sample is one dot point's, and the record names it;
//   mixed  some shape belongs to another dot point, to several, or to none the topic lists: the cell is NOT offered for any dot point
//          (the generator exposes no form id to split it by, so a request cannot be answered with only the right shape).
// The record carries a digest of the sampled questions' content hashes: if a generator changes, the record is stale, the check fails, and
// the cell is read again. Years 7 to 10 have no records: only an author-numbered question (the bank) or a question that names its own
// dot point (a payload declaration) is offered for a dot point there.
//   node tools/nsw-dotpoint-content.mjs --check        verify the records are current and complete, and the generated table matches
//   node tools/nsw-dotpoint-content.mjs --list-mixed   the cells and dot points that are not offered because their cell mixes dot points
//   node tools/nsw-dotpoint-content.mjs --record FILE  write the records from a reading (FILE: {"generator|level": {"w": {dotPointId|several|none: samples}}})
//   node tools/nsw-dotpoint-content.mjs                regenerate client/src/engine/nswDotpointContent.js from the records
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REVIEW = path.join(ROOT, 'tools/nsw-dotpoint-content-review.json');
const OUT = path.join(ROOT, 'client/src/engine/nswDotpointContent.js');
export const SAMPLES = 40;
process.env.NODE_ENV ??= 'test';
process.env.PRI_EDITION = 'prithagoras';
const G = await import(path.join(ROOT, 'client/src/engine/generators/index.js'));
await G.loadAllBanks();
const { SUBTOPICS, dotpointsFor } = await import(path.join(ROOT, 'client/src/engine/curriculum.js'));
const { NSW_ISSUED_CELLS } = await import(path.join(ROOT, 'client/src/engine/nswIssuedCells.js'));

/** The sampled questions of a cell, as the review read them. */
function sample(generator, level) {
  const out = [];
  for (let i = 1; i <= SAMPLES; i++) { try { const q = G.generateQuestion(generator, level, i * 7919 + level); if (q) out.push(q); } catch { /* not issued */ } }
  return out;
}
const digestOf = qs => createHash('sha256').update(qs.map(q => q.contentHash).join('|')).digest('hex').slice(0, 16);
/** The cells a review must cover: Years 11 and 12, issued, with at least one sampled question whose dot point comes from a table. */
export function cellsToReview() {
  const cells = [];
  for (const s of SUBTOPICS) {
    if (s.year < 11 || !NSW_ISSUED_CELLS[s.id]) continue;
    for (const level of NSW_ISSUED_CELLS[s.id]) {
      const qs = sample(s.id, level);
      if (qs.some(q => q.dotpointSource !== 'payload')) cells.push({ generator: s.id, level, digest: digestOf(qs), samples: qs.length });
    }
  }
  return cells;
}
const readReviews = () => (existsSync(REVIEW) ? JSON.parse(readFileSync(REVIEW, 'utf8')) : []);

export function render(reviews = readReviews()) {
  const table = {};
  for (const r of reviews) if (r.verdict === 'pure') ((table[r.generator] ||= {})[r.dotpoint] ||= []).push(r.level);
  const rows = Object.entries(table).map(([g, dps]) => `  '${g}': {\n${Object.entries(dps).map(([id, l]) => `    '${id}': [${l.sort((a, b) => a - b).join(', ')}]`).join(',\n')}\n  }`);
  return `// GENERATED by tools/nsw-dotpoint-content.mjs from tools/nsw-dotpoint-content-review.json — do not edit.
// For each Year 11 and 12 generator and dot point: the levels at which a content review READ a sample of the generator's questions and found
// every question shape on that dot point. A generated question whose dot point comes from the registry or the generator's cell table is
// served for a dot point request only at a level listed here; see the header of tools/nsw-dotpoint-content.mjs.
export const NSW_DOTPOINT_CONTENT = Object.freeze({
${rows.join(',\n')}
});
`;
}

function problems() {
  const out = [];
  const reviews = readReviews();
  const by = new Map(reviews.map(r => [`${r.generator}|${r.level}`, r]));
  for (const c of cellsToReview()) {
    const r = by.get(`${c.generator}|${c.level}`);
    if (!r) out.push(`${c.generator} level ${c.level}: no review record`);
    else if (r.digest !== c.digest) out.push(`${c.generator} level ${c.level}: the generator's questions changed since they were read (record ${r.digest}, now ${c.digest}); read the cell again`);
  }
  for (const r of reviews) {
    if (r.verdict === 'pure' && !(dotpointsFor(r.generator).some(d => d.id === r.dotpoint))) out.push(`${r.generator} level ${r.level}: names a dot point the topic does not have (${r.dotpoint})`);
    if (r.verdict === 'pure' && (Object.keys(r.found).length !== 1 || r.found[r.dotpoint] === undefined)) out.push(`${r.generator} level ${r.level}: a pure record must hold one dot point only`);
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const arg = process.argv[2] || '';
  if (arg === '--record') {
    const reading = JSON.parse(readFileSync(process.argv[3], 'utf8'));
    const out = [];
    for (const c of cellsToReview()) {
      const found = reading[`${c.generator}|${c.level}`]?.w;
      if (!found) throw new Error(`no reading for ${c.generator} level ${c.level}`);
      const ids = Object.keys(found);
      const pure = ids.length === 1 && !['several', 'none'].includes(ids[0]);
      out.push({ generator: c.generator, level: c.level, verdict: pure ? 'pure' : 'mixed', dotpoint: pure ? ids[0] : null, found, samples: c.samples, digest: c.digest });
    }
    writeFileSync(REVIEW, JSON.stringify(out, null, 1) + '\n');
    writeFileSync(OUT, render(out));
    console.log(`recorded ${out.length} cells (${out.filter(r => r.verdict === 'pure').length} pure, ${out.filter(r => r.verdict === 'mixed').length} mixed)`);
  } else if (arg === '--list-mixed') {
    for (const r of readReviews().filter(x => x.verdict === 'mixed')) console.log(`${r.generator} level ${r.level}: ${Object.entries(r.found).map(([k, v]) => `${k}=${v}`).join(' ')}`);
  } else if (arg === '--check') {
    const p = problems();
    let table = false; try { table = readFileSync(OUT, 'utf8') === render(); } catch { /* missing */ }
    if (!table) p.push('client/src/engine/nswDotpointContent.js does not match the records; run node tools/nsw-dotpoint-content.mjs');
    const reviews = readReviews();
    console.log(p.length ? `NSW DOTPOINT CONTENT: FAIL\n  · ${p.slice(0, 20).join('\n  · ')}` : `NSW DOTPOINT CONTENT: PASS, ${reviews.length} cells read (${reviews.filter(r => r.verdict === 'pure').length} pure, ${reviews.filter(r => r.verdict === 'mixed').length} mixed, not offered), every record current`);
    process.exit(p.length ? 1 : 0);
  } else { writeFileSync(OUT, render()); console.log(`wrote ${path.relative(ROOT, OUT)}`); }
}
