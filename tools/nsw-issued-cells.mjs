#!/usr/bin/env node
// Writes (or with --check verifies) client/src/engine/nswIssuedCells.js: the
// device's copy of the cells a Prithagoras server issues. The server's ledger
// (server/platform/nswBanks.js NSW_BANK_LEDGER) is the authority; this file is
// only ever generated from it.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'client/src/engine/nswIssuedCells.js');
const { NSW_BANK_LEDGER } = await import(path.join(ROOT, 'server/platform/nswBanks.js'));

export function render() {
  const rows = NSW_BANK_LEDGER.filter(e => e.issued)
    .map(e => `  '${e.generator}': [${e.cells.filter(c => c.issued).map(c => c.difficulty).join(', ')}]`);
  return `// GENERATED by tools/nsw-issued-cells.mjs from server/platform/nswBanks.js — do not edit.
// The (generator, difficulty) cells a Prithagoras server issues. The server's
// ledger is the authority; client/test/nsw-offer-check.mjs fails if this copy
// differs from it. Regenerate: node tools/nsw-issued-cells.mjs
export const NSW_ISSUED_CELLS = Object.freeze({
${rows.join(',\n')}
});
`;
}

const text = render();
if (process.argv.includes('--check')) {
  const same = (() => { try { return readFileSync(OUT, 'utf8') === text; } catch { return false; } })();
  console.log(same ? 'NSW ISSUED CELLS: PASS — the device copy matches the server ledger' : 'NSW ISSUED CELLS: FAIL — run node tools/nsw-issued-cells.mjs');
  process.exit(same ? 0 : 1);
} else if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
