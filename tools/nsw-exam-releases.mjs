#!/usr/bin/env node
// Pri Learning · "NSW papers: what is released and why" (plan mission G4).
//
// Renders docs/content/nsw-papers-released.md from the release check itself
// (client/src/engine/nswExams.js on the server's pool, server/platform/
// nswExamPool.js), so the page can never say more than the check decides.
// client/test/nsw-exams-check.mjs fails when the committed page is stale.
//
//   node tools/nsw-exam-releases.mjs           print the page
//   node tools/nsw-exam-releases.mjs --write   write docs/content/nsw-papers-released.md
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { NSW_EXAM_BLUEPRINTS, NSW_MIN_FORMS_PER_SLOT, NSW_RELEASE_FLOOR, NSW_EXAM_LABEL, outcomesOf, tallyOf, nswPaperTitle } from '../client/src/engine/nswExams.js';
import { NSW_EXAM_POOL, releaseOf, outcomeNamed } from '../server/platform/nswExamPool.js';

const PAGE = new URL('../docs/content/nsw-papers-released.md', import.meta.url);
const named = codes => codes.map(c => { const o = outcomeNamed(c); return `${o.name} (${c})`; }).join('; ') || '—';

export function renderReleases(pool = NSW_EXAM_POOL) {
  const lines = [
    '# NSW papers: what is released and why',
    '',
    '<!-- Generated by tools/nsw-exam-releases.mjs from the release check. Do not edit by hand; run `node tools/nsw-exam-releases.mjs --write`. -->',
    '',
    `Prithagoras offers timed papers shaped like an HSC examination, each an "${NSW_EXAM_LABEL}": sealed and marked by the server on final answers only, with no HSC mark, band, ATAR or prediction. An outcome is **covered** when every slot on it can be filled from at least ${NSW_MIN_FORMS_PER_SLOT} distinct approved question forms. An approved form is one (generator, difficulty) cell the Prithagoras edition issues (\`server/platform/nswBanks.js\`); one form yields many questions with different numbers but counts once.`,
    '',
    `- Every slot covered: the whole paper is released.`,
    `- Otherwise a **partial** paper (only the slots that can be filled) is released when at least ${NSW_RELEASE_FLOOR * 100}% of the course's Year 12 outcomes (from the G2 model) are covered. It is titled "Practice paper — N of M Year 12 outcomes", never an HSC paper or a trial; its marks and working time are scaled to what it examines; and the Exams page, the paper and the result name every outcome it leaves out.`,
    `- Below that floor the paper is refused.`,
    '',
    `The pool today: ${pool.length} approved forms. Blueprint structures (times, marks, section sizes) follow NESA's published HSC examination specifications for the 2024 syllabuses, first examined in 2027 (\`docs/research/NSW_HSC_CURRICULUM_ASSESSMENT_AUTHORITY.md\` §5.3). Which outcome each slot is on is Pri's own design: every Year 12 outcome of the examined course has slots. No NESA paper, question, marking guideline or reference sheet is reproduced. The platform has no authored formula sheet yet, so none is shown.`,
    '',
    '| Paper | State | Year 12 outcomes covered | Sat as | Omitted outcomes |',
    '| --- | --- | --- | --- | --- |'
  ];
  for (const b of NSW_EXAM_BLUEPRINTS) {
    const r = releaseOf(b, pool);
    const t = tallyOf(b);
    const state = r.released ? (r.full ? 'released' : 'released (partial)') : 'refused';
    const sat = r.released ? `"${nswPaperTitle(b, r)}": ${r.included.length} questions, ${r.marks} marks, ${b.readingMin} min reading + ${r.workingMin} min` : `designed: ${t.items} questions, ${t.totalMarks} marks, ${b.readingMin} + ${b.workingMin} min`;
    lines.push(`| ${b.label} | ${state} | ${r.year12.covered} of ${r.year12.total} (${Math.round(100 * r.year12.share)}%) | ${sat} | ${named(r.omittedOutcomes)} |`);
  }
  lines.push('');
  for (const b of NSW_EXAM_BLUEPRINTS) {
    const r = releaseOf(b, pool);
    lines.push(`## ${b.label}`, '', `Source: ${b.source.document} — ${b.source.url} (read ${b.source.accessed}). Examined: ${b.source.examined}`, '',
      '| Outcome | Focus area | Year | Slots | Marks | Approved forms | Covered |', '| --- | --- | --- | --- | --- | --- | --- |');
    for (const code of outcomesOf(b)) {
      const slots = r.slots.filter(s => s.outcome === code);
      const o = outcomeNamed(code);
      lines.push(`| ${code} | ${o.name} | ${o.year ?? ''} | ${slots.length} | ${slots.reduce((n, s) => n + s.marks, 0)} | ${r.formsByOutcome[code]} | ${slots.every(s => s.forms >= NSW_MIN_FORMS_PER_SLOT) ? 'yes' : 'no'} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const page = renderReleases();
  if (process.argv.includes('--write')) { writeFileSync(PAGE, page); console.log(`wrote ${fileURLToPath(PAGE)}`); }
  else process.stdout.write(page);
}
