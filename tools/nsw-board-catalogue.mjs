#!/usr/bin/env node
// Writes (or with --check verifies) client/src/engine/nswBoardCatalogue.js: the
// device's copy of the NSW courses the syllabus board draws (Progress, both
// editions' shared board; engine/syllabusBoard.js).
//
// The NSW curriculum model stays server-side and is imported by nothing in
// client/src (client/test/nsw-curriculum-check.mjs), exactly as the issued
// cells are (tools/nsw-issued-cells.mjs). This file is only ever generated
// from it and from the server's own curriculum response:
//   · one node per outcome code of each current syllabus, grouped by focus
//     area (codes and focus-area/content-group names only: no NESA outcome or
//     dot-point wording is stored, research §5.7);
//   · for each Pri dot point the crosswalk located, the outcome codes it sits
//     at — the board credits an answer to an outcome through this map only;
//   · for each outcome, the practice the server issues on it (generator and
//     dot point) — the first issued target — so "Practise this" opens real
//     practice or is not offered.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'client/src/engine/nswBoardCatalogue.js');
const model = await import(path.join(ROOT, 'client/src/engine/curriculum-nsw/index.js'));
const { nswCurriculumResponse } = await import(path.join(ROOT, 'server/platform/nswBanks.js'));

const K10 = model.NSW_MATHEMATICS_K10_2022;
const STD = model.NSW_MATHEMATICS_STANDARD_2024;
const ADV = model.NSW_MATHEMATICS_ADVANCED_2024;
const EXT1 = model.NSW_MATHEMATICS_EXTENSION1_2024;
const EXT2 = model.NSW_MATHEMATICS_EXTENSION2_2024;

// The courses a student can be on. `pick` chooses the focus areas of the course.
const COURSES = [
  { key: 'k10-stage4', name: 'Mathematics K–10 · Stage 4', syllabus: K10, pick: fa => fa.stage === 4, blueprint: null, firstHsc: null },
  { key: 'k10-stage5', name: 'Mathematics K–10 · Stage 5', syllabus: K10, pick: fa => fa.stage === 5, blueprint: null, firstHsc: null },
  { key: 'standard-1', name: 'Mathematics Standard 1', syllabus: STD, pick: fa => !fa.course || fa.course === 'Standard 1', blueprint: 'nsw-hsc-standard-1-2027', firstHsc: 2027 },
  { key: 'standard-2', name: 'Mathematics Standard 2', syllabus: STD, pick: fa => !fa.course || fa.course === 'Standard 2', blueprint: 'nsw-hsc-standard-2-2027', firstHsc: 2027 },
  { key: 'advanced', name: 'Mathematics Advanced', syllabus: ADV, pick: () => true, blueprint: 'nsw-hsc-advanced-2027', firstHsc: 2027 },
  { key: 'extension-1', name: 'Mathematics Extension 1', syllabus: EXT1, pick: () => true, blueprint: 'nsw-hsc-extension-1-2027', firstHsc: 2027 },
  { key: 'extension-2', name: 'Mathematics Extension 2', syllabus: EXT2, pick: () => true, blueprint: 'nsw-hsc-extension-2-2027', firstHsc: 2027 }
];

const slug = text => String(text).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const q = s => JSON.stringify(s);

function practiceByCode() {
  const out = new Map();
  for (const s of nswCurriculumResponse().syllabuses) {
    for (const group of s.subtopics) {
      for (const dp of group.dotpoints) {
        // [generator, 0-based dot point ordinal] of each issued target, in the server's order.
        out.set(dp.code, dp.practice.map(t => [t.generator, Number(String(t.dotpoint).split('.').pop()) - 1]));
      }
    }
  }
  return out;
}

export function render() {
  const practice = practiceByCode();
  const courses = COURSES.map(c => {
    const groups = c.syllabus.focusAreas.filter(c.pick).map(fa => {
      const id = `${slug(fa.name)}${fa.year ? `-y${fa.year}` : ''}${fa.stage ? `-s${fa.stage}` : ''}${fa.course ? `-${slug(fa.course)}` : ''}`;
      // The first issued target on the outcome, or null: what "Practise this" opens.
      const outcomes = fa.outcomes.map(code => `{ code: ${q(code)}, practise: ${q((practice.get(code) || [])[0] || null)} }`);
      return `      { id: ${q(id)}, name: ${q(fa.name)}, year: ${fa.year ?? 'null'}, stage: ${fa.stage ?? 'null'}, kind: ${q(fa.kind ?? null)}, contentGroups: ${q([...(fa.contentGroups || [])])},\n        outcomes: [${outcomes.join(', ')}] }`;
    });
    return `  ${q(c.key)}: {\n    key: ${q(c.key)}, name: ${q(c.name)}, syllabus: ${q(c.syllabus.id)}, version: ${q(c.syllabus.version)}, firstHsc: ${c.firstHsc ?? 'null'}, blueprint: ${q(c.blueprint)},\n    groups: [\n${groups.join(',\n')}\n    ]\n  }`;
  });
  const located = [];
  for (const row of model.LEGACY_CROSSWALK) {
    if (!row.subtopicId) continue;
    row.dotpoints.forEach((codes, i) => { if (codes.length) located.push(`  ${q(`${row.subtopicId}.${i + 1}`)}: ${q([...codes])}`); });
  }
  return `// GENERATED by tools/nsw-board-catalogue.mjs from the server's NSW model and
// curriculum response (server/platform/nswBanks.js) — do not edit.
// The NSW courses the syllabus board draws: one node per outcome code, grouped
// by focus area. Codes and focus-area/content-group names only — no NESA
// outcome or dot-point wording is stored. client/test/syllabus-board-check.mjs
// fails if this copy differs from the model. Regenerate: node tools/nsw-board-catalogue.mjs
export const NSW_BOARD_COURSES = Object.freeze({
${courses.join(',\n')}
});

/** Pri dot point id → the current outcome codes the crosswalk located it at. */
export const NSW_DOTPOINT_OUTCOMES = Object.freeze({
${located.join(',\n')}
});
`;
}

const text = render();
if (process.argv.includes('--check')) {
  const same = (() => { try { return readFileSync(OUT, 'utf8') === text; } catch { return false; } })();
  console.log(same ? 'NSW BOARD CATALOGUE: PASS — the device copy matches the model' : 'NSW BOARD CATALOGUE: FAIL — run node tools/nsw-board-catalogue.mjs');
  process.exit(same ? 0 : 1);
} else if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
