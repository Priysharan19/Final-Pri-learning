#!/usr/bin/env node
// Pri Learning · advertised level coverage (phase 4)
//
// Every track the product offers advertises a difficulty window (CBSE D1–D3,
// JEE Main D2–D4, JEE Advanced D3–D4, Olympiad D1–D4). This report proves, for
// each track and class the picker shows, that every advertised level exists:
// some chapter in scope serves an authored form at exactly that level, and every
// chapter serves its track's hardest level. It reads indiaRequestableDifficulties,
// the same function the picker and the practice route use.
//
// It counts authored forms. It is not a human review, a rights clearance or a
// claim that a form matches the depth of the named examination.
//
//   node tools/advertised-level-coverage.mjs           # write the report
//   node tools/advertised-level-coverage.mjs --check   # fail when stale or when a level is missing
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SRC = new URL('../client/src/', import.meta.url).href;
const OUT = fileURLToPath(new URL('../docs/release/evidence/advertised-level-coverage.md', import.meta.url));
const { IN_TRACKS } = await import(`${SRC}engine/curriculum-in.js`);
const { indiaScope, indiaDifficultyWindow, indiaRequestableDifficulties } = await import(`${SRC}engine/indiaProduct.js`);
const { JEE_ADV_COMPLEX_D4_CERTIFICATION: cert } = await import(`${SRC}engine/ncert/jee-2026-complex-d4-certification.js`);

const VIEWS = [
  ...[7, 8, 9, 10, 11, 12].map(grade => ({ track: 'cbse', grade })),
  ...[11, 12].map(grade => ({ track: 'jee-main', grade })),
  ...[11, 12].map(grade => ({ track: 'jee-advanced', grade })),
  ...[7, 8, 9, 10, 11, 12].map(grade => ({ track: 'olympiad', grade }))
];

const rows = [], missing = [];
for (const { track, grade } of VIEWS) {
  const { floor, ceiling } = indiaDifficultyWindow(track, grade);
  const chapters = indiaScope(track, grade);
  const levels = [];
  for (let d = floor; d <= ceiling; d++) {
    let ch = 0, dp = 0, dpTotal = 0;
    for (const c of chapters) {
      if (indiaRequestableDifficulties(c, { track, grade }).includes(d)) ch++;
      (c.dotpoints || []).forEach((_, i) => { dpTotal++; if (indiaRequestableDifficulties(c, { track, grade, dotpoint: i }).includes(d)) dp++; });
    }
    levels.push({ d, ch, dp, dpTotal });
    if (!ch) missing.push(`${IN_TRACKS[track].name} Class ${grade}: D${d} is advertised but no chapter serves it`);
  }
  const noHardest = chapters.filter(c => !indiaRequestableDifficulties(c, { track, grade }).includes(ceiling));
  for (const c of noHardest) missing.push(`${IN_TRACKS[track].name} Class ${grade}: ${c.id} has no form at D${ceiling}`);
  if (!chapters.length) missing.push(`${IN_TRACKS[track].name} Class ${grade}: no chapters in scope`);
  rows.push({ track, name: IN_TRACKS[track].name, grade, floor, ceiling, chapters: chapters.length, levels, noHardest: noHardest.length });
}

const L = [];
L.push('# Advertised level coverage — every level the product offers exists', '');
L.push('Generated by `node tools/advertised-level-coverage.mjs`. Do not edit by hand; `npm run test:levels` fails when this file is stale or when any advertised level has no form.', '');
L.push('**What this is.** For each track and class the picker shows, the number of chapters (and dot points) that serve an authored form at exactly each advertised level, read from `indiaRequestableDifficulties`.', '');
L.push('**What this is not.** It is not a human maths review, a rights clearance, past-paper provenance, or a claim that a form reaches the depth of the examination a track is named after. Dot-point gaps are listed in `india-difficulty-coverage.md`; the picker never offers a level a dot point lacks.', '');
L.push('| Track | Class | Window | Chapters | ' + [1, 2, 3, 4].map(d => `D${d} chapters (dot points)`).join(' | ') + ' | Chapters without the hardest level |');
L.push('|---|---:|---|---:|' + '---:|'.repeat(4) + '---:|');
for (const r of rows) {
  const cells = [1, 2, 3, 4].map(d => { const l = r.levels.find(x => x.d === d); return l ? `${l.ch} (${l.dp}/${l.dpTotal})` : 'not advertised'; });
  L.push(`| ${r.name} | ${r.grade} | D${r.floor}–D${r.ceiling} | ${r.chapters} | ${cells.join(' | ')} | ${r.noHardest} |`);
}
L.push('', `**Result:** ${missing.length ? 'FAIL — ' + missing.length + ' advertised level(s) missing' : 'every advertised level exists in every track and class view'}.`, '');
if (missing.length) L.push(...missing.map(m => '- ' + m), '');
L.push('## Content held back from the picker', '');
L.push(`- JEE Advanced Complex Numbers: ${cert.forms.length} original forms meet the automated D4 structural rubric (#408). Human maths review: ${cert.humanMathsReview}. Rights review: ${cert.rightsReview}. Live graded: ${cert.liveGraded ? 'yes' : 'no'} — they are proof/description items and their answers stay in the server escrow lane (#395).`);
L.push('- CBSE Class IX 2026–27 study packs (#472): 105 original items plus 10 corrections, draft-only and not wired into the app.', '');
const text = L.join('\n');

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== text) { console.error('ADVERTISED LEVELS: FAIL — docs/release/evidence/advertised-level-coverage.md is stale; run node tools/advertised-level-coverage.mjs'); process.exit(1); }
  if (missing.length) { console.error('ADVERTISED LEVELS: FAIL —\n' + missing.join('\n')); process.exit(1); }
  const cells = rows.reduce((s, r) => s + r.levels.length, 0);
  console.log(`ADVERTISED LEVELS: PASS — ${cells}/${cells} advertised (track, class, level) cells served across ${rows.length} views; every chapter serves its hardest level`);
} else { writeFileSync(OUT, text); console.log('wrote ' + OUT + (missing.length ? ` (${missing.length} missing)` : '')); }
