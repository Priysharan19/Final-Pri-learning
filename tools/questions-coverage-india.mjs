#!/usr/bin/env node
// Pri Learning · Priyabhata question coverage (all skills): instances, structural forms and
// diagram coverage, against the owner's targets. Instances and forms come from the committed
// question-capacity report (tools/question-capacity.mjs); diagram coverage is sampled here.
//   node tools/questions-coverage-india.mjs [YYYY-MM-DD]   # writes docs/content/questions-coverage-india-<date>.md
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const date = process.argv[2] || new Date().toISOString().slice(0, 10);
const report = readFileSync(`${ROOT}docs/content/question-capacity.md`, 'utf8');
const section = report.slice(report.indexOf('## Priyabhata'));
const rows = [...section.matchAll(/^\| `([^`]+)` \| (\d+) \| (≥ )?([\d.]+[kM]?) \| (\d+) \| ([^|]+) \|$/gm)].map(m => ({ id: m[1], cells: +m[2], lower: !!m[3], instances: m[4], forms: +m[5], below: m[6].trim() }));
const { generateQuestion, loadAllBanks } = await import('../client/src/engine/generators/index.js');
await loadAllBanks();
const seedAt = i => Number((BigInt(i) * 2654435761n) % 4294967291n);
for (const r of rows) {
  let withFigure = 0, drawn = 0;
  for (let d = 1; d <= 4; d++) for (let i = 1; i <= 60; i++) {
    try { const q = generateQuestion(r.id, d, seedAt(i)); drawn += 1; if (q.figure || q.diagram || q.plot || q.graph) withFigure += 1; } catch { /* a cell the skill does not serve */ }
  }
  r.figure = drawn ? Math.round((100 * withFigure) / drawn) : 0;
}
const short = rows.filter(r => r.below !== '—');
const withFig = rows.filter(r => r.figure > 0);
const byClass = {};
for (const r of rows) { const k = r.id.match(/^(c\d+|olymp)/)?.[1] || 'other'; (byClass[k] ||= []).push(r); }
let md = `# Priyabhata question coverage — ${date}\n\n<!-- Generated by tools/questions-coverage-india.mjs from docs/content/question-capacity.md. Do not edit by hand. -->\n\nTargets (owner, Nov 2026): at least 10,000 distinct instances and at least 5 structural forms per skill. Instances and forms are the question-capacity tool's synthetic measurement; diagram coverage is the share of 240 sampled questions per skill (60 seeds × 4 difficulties) that carry a figure, diagram, plot or graph. SYNTHETIC: generators run in-process; no student or examiner evidence.\n\n`;
md += `**${rows.length} Priyabhata skills measured. ${rows.length - short.length} meet both targets; ${short.length} are below.** ${withFig.length} skills carry a generated figure in at least one sampled question.\n\n`;
md += `## Below target\n\n`;
md += short.length ? short.map(r => `- \`${r.id}\` — ${r.instances} instances, ${r.forms} forms (${r.below})`).join('\n') : 'None.';
md += `\n\n## Diagrams\n\nSkills whose questions benefit from a diagram (geometry, mensuration, coordinate geometry, graphs, vectors) and carry none in any sampled question are listed here as the diagram gap. The extra structural forms added in the capacity work (\`generators/forms\`) are text-only; a generated diagram needs the figure kit and its own accuracy tests and is tracked separately.\n\n`;
const GEO = /(triang|circle|quadrilat|geometry|mensur|area|volume|surface|coordinate|vector|graph|chart|solid|symmetr|construct|angle|line|section|distance|tangent|sector|conic|parabola|3d|congru|bpt|twins|connecting|common-ground|perpendicular|heron|euclid|statistics|data)/;
const gap = rows.filter(r => GEO.test(r.id) && r.figure === 0);
md += gap.length ? gap.map(r => `- \`${r.id}\``).join('\n') : 'None.';
md += `\n\n## Every skill\n\n`;
for (const [k, list] of Object.entries(byClass)) {
  md += `### ${k}\n\n| Skill | Instances | Forms | Diagram share | Below target |\n| --- | --- | --- | --- | --- |\n`;
  for (const r of list.sort((a, b) => a.id.localeCompare(b.id))) md += `| \`${r.id}\` | ${r.lower ? '≥ ' : ''}${r.instances} | ${r.forms} | ${r.figure}% | ${r.below} |\n`;
  md += '\n';
}
writeFileSync(`${ROOT}docs/content/questions-coverage-india-${date}.md`, md);
console.log(`wrote docs/content/questions-coverage-india-${date}.md — ${rows.length} skills, ${short.length} below target, ${gap.length} diagram-gap geometry skills`);
