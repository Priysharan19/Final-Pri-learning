#!/usr/bin/env node
// Writes (or with --check verifies) client/src/engine/nswDotpointExact.js: for each issued NSW generator, the
// levels at which a request for a dot point is answered ONLY by questions that are on that dot point: an author-numbered bank question, a question that names its own dot point, or a generated
// question at a level whose content a review READ and found pure (tools/nsw-dotpoint-content.mjs). The registry table alone is not trusted.
//
// Launch QA 26 Nov 2026 (SHOULD FIX 3): 17 percent of dot point requests were answered with a question of a sibling
// dot point, because a cell that names two dot points cannot say which one any question is (generateQuestion's
// `dotpointExact`). A level counts here only when the server's own picker, asked REQUESTS times with fixed draws, serves an
// exact question at least MIN_SERVED times. A level that is not listed is never offered for the dot point, and
// the server never serves a question that is not exact (server/platform/practice.js seekQuestion).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'client/src/engine/nswDotpointExact.js');
export const REQUESTS = 10;
export const MIN_SERVED = 9;
process.env.NODE_ENV ??= 'test';
process.env.PRI_EDITION = 'prithagoras';   // the author's question bank is Prithagoras-only and is part of what a dot point request is answered with
const { dotpointsFor } = await import(path.join(ROOT, 'client/src/engine/curriculum.js'));
const { NSW_ISSUED_CELLS } = await import(path.join(ROOT, 'client/src/engine/nswIssuedCells.js'));
const { chooseQuestion, ensureBanks } = await import(path.join(ROOT, 'server/platform/practice.js'));
const { ensureQbank } = await import(path.join(ROOT, 'server/platform/qbankPack.js'));
const { bankPolicy } = await import(path.join(ROOT, 'server/platform/editionBanks.js'));
await ensureBanks();
await ensureQbank(process.env, { strict: true });
const banks = bankPolicy('prithagoras');
const lcg = a => () => { a = (Math.imul(a, 1664525) + 1013904223) >>> 0; return a; };

/** The levels at which the server's own picker answers a dot point request, nine times in ten at least, and only with exact questions. */
export function compute() {
  const out = {};
  for (const [generator, issued] of Object.entries(NSW_ISSUED_CELLS)) {
    for (const dp of dotpointsFor(generator)) {
      const levels = [];
      // Every issued level, not only the levels the engine's forms name: the author's questions are numbered to a dot point at a level of
      // their own, which the generators' form table does not know.
      for (const d of issued) {
        let served = 0;
        for (let i = 0; i < REQUESTS; i++) {
          try {
            const { q } = chooseQuestion({ generator, difficulty: d, mode: 'practice', avoid: new Set(), dotpoint: dp.id, trap: null, written: false, band: null },
              null, { draw: lcg(i * 977 + d * 31 + 7), banks });
            // At the level asked for: the engine snaps a level a dot point has no form at to its nearest one, which is another level.
            if (q.dotpointExact === true && Number(q.difficulty) === d) served++;
          } catch { /* refused: nothing exact */ }
        }
        if (served >= MIN_SERVED) levels.push(d);
      }
      (out[generator] ||= {})[dp.id] = levels;
    }
  }
  return out;
}

export function render(table = compute()) {
  const rows = Object.entries(table).map(([g, dps]) => `  '${g}': {\n${Object.entries(dps).map(([id, l]) => `    '${id}': [${l.join(', ')}]`).join(',\n')}\n  }`);
  return `// GENERATED by tools/nsw-dotpoint-exact.mjs — do not edit.
// For each issued NSW generator and dot point: the levels at which a request for that dot point is answered only by
// questions on it (the server's own picker, asked ${REQUESTS} times with fixed draws, serves an exact question at least ${MIN_SERVED} times). A level not listed is not offered
// for the dot point, and the server refuses it rather than serve a sibling's question. Regenerate: node tools/nsw-dotpoint-exact.mjs
export const NSW_DOTPOINT_EXACT = Object.freeze({
${rows.join(',\n')}
});
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes('--check')) {
    const same = (() => { try { return readFileSync(OUT, 'utf8') === text; } catch { return false; } })();
    console.log(same ? 'NSW DOTPOINT EXACT: PASS, the exact-level table matches a fresh draw' : 'NSW DOTPOINT EXACT: FAIL, run node tools/nsw-dotpoint-exact.mjs');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
