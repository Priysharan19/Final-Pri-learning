#!/usr/bin/env node
// Pri Learning · CBSE 2026–27 chapter and competency crosswalk (#451)
//
// One table per class, 7–12, built from the engine's own chapter data and the
// official references already recorded in the repository. Each app chapter is
// tagged core (CBSE standard course), and the JEE and Olympiad tracks that
// reuse it are listed as advanced / optional enrichment, never as CBSE-mandated.
// Omissions are listed explicitly. Where the repository holds no captured
// official chapter or competency list, the row says so instead of mapping by
// title alone.
//
// This is an author audit. No teacher or examiner has signed it off, and it
// supports no "certified 2026–27" claim.
//
//   node tools/cbse-2026-27-crosswalk.mjs           # write the report
//   node tools/cbse-2026-27-crosswalk.mjs --check   # fail when stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SRC = new URL('../client/src/', import.meta.url).href;
const OUT = fileURLToPath(new URL('../docs/release/evidence/cbse-2026-27-crosswalk.md', import.meta.url));
const { indiaScope } = await import(`${SRC}engine/indiaProduct.js`);
const { CLASS9_202627_ACCEPTANCE_CROSSWALK: c9 } = await import(`${SRC}engine/ncert/class9-2026-27-competency-crosswalk.js`);

export const SOURCES = {
  7: { basis: 'NCERT Ganita Prakash Grade 7 (Parts I and II), chapter list as recorded in class7-2026-27-syllabus.js', competencyMapCaptured: false },
  8: { basis: 'NCERT Grade 8 chapter list as recorded in the class8 syllabus files; NCERT Grade 8 bridge programme applies', competencyMapCaptured: false },
  9: { basis: 'CBSE 2026–27 Class IX Mathematics (standard), https://cbseacademic.nic.in/web_material/CurriculumMain27/SecPart1/Maths_SecP1IX_2026-27.pdf, pages 7–12', competencyMapCaptured: true },
  10: { basis: 'CBSE Class X Mathematics unit blueprint (examUnit / examUnitMarks in curriculum data), https://cbseacademic.nic.in/web_material/CurriculumMain27/SecPart1/Maths_SecP1X_2026-27.pdf', competencyMapCaptured: false },
  11: { basis: 'CBSE Senior Secondary Mathematics unit blueprint (examUnit / examUnitMarks in curriculum data)', competencyMapCaptured: false },
  12: { basis: 'CBSE Senior Secondary Mathematics unit blueprint (examUnit / examUnitMarks in curriculum data)', competencyMapCaptured: false }
};

const jee = new Set([...indiaScope('jee-main', 12), ...indiaScope('jee-advanced', 12)].map(c => c.id));
const olymp = new Set([7, 8, 9, 10, 11, 12].flatMap(g => indiaScope('olympiad', g).map(c => c.id)));
const L = ['# CBSE 2026–27 crosswalk — app chapters against the official course (#451)', ''];
L.push('Generated by `node tools/cbse-2026-27-crosswalk.mjs`. Do not edit by hand; `--check` fails when it is stale.', '');
L.push('**Status: author audit, not certified.** No teacher or examiner has signed this off. It must not be used for a "certified 2026–27" or "syllabus-complete" claim. External sources are links only.', '');
L.push('**Tags.** `core` = the chapter is part of the standard CBSE course for that class. `advanced` = the same chapter is also served on a JEE track (exam-specific enrichment, not CBSE-mandated). `optional` = Olympiad enrichment. CBSE Class IX *Mathematics at Advanced Level* is a separate optional subject and is not mapped here; it is not JEE Advanced.', '');
const omissions = [];
for (const g of [7, 8, 9, 10, 11, 12]) {
  const s = SOURCES[g], chapters = indiaScope('cbse', g);
  L.push(`## Class ${g}`, '', `Official basis: ${s.basis}.`, '');
  L.push(`Competency-level map captured: ${s.competencyMapCaptured ? 'yes (Class IX crosswalk, partial — see omissions)' : '**no** — chapters are matched to the recorded chapter/unit list only; a competency-level map is still required'}.`, '');
  L.push('| App chapter | Title | Official unit (marks) | Tags | Dot points |', '|---|---|---|---|---:|');
  for (const c of chapters) {
    const unit = c.examUnitName ? `${c.examUnitName}${c.examUnitMarks ? ` (${c.examUnitMarks})` : ''}` : '—';
    const tags = ['core', ...(jee.has(c.id) ? ['advanced'] : []), ...(olymp.has(c.id) ? ['optional'] : [])].join(', ');
    L.push(`| \`${c.id}\` | ${c.name} | ${unit} | ${tags} | ${(c.dotpoints || []).length} |`);
  }
  L.push('');
  if (g === 9) {
    const byChapter = new Map();
    for (const o of c9.outcomes) { const k = byChapter.get(o.chapter) || { partial: 0, uncovered: 0 }; o.state === 'uncovered' ? k.uncovered++ : k.partial++; byChapter.set(o.chapter, k); }
    for (const [ch, k] of byChapter) omissions.push(`Class 9 — ${ch}: no app chapter; ${k.partial} outcome(s) partially evidenced by draft study packs, ${k.uncovered} uncovered`);
  }
  if (!s.competencyMapCaptured) omissions.push(`Class ${g} — competency-level map not captured from the official 2026–27 document`);
}
L.push('## Omissions and open items', '', ...omissions.map(o => '- ' + o), '');
L.push('- Per-example `core` / `optional` / `advanced` tags for the 1,371 Notes worked examples (#450) are not yet assigned; the chapter tags above are not a substitute.');
L.push('- Independent stratified solving of every authored archetype, diagram-to-step validation and teacher/examiner sign-off remain required (#451 items 3 and 5).', '');
const text = L.join('\n');
if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== text) { console.error('CBSE 2026–27 CROSSWALK: FAIL — report is stale; run node tools/cbse-2026-27-crosswalk.mjs'); process.exit(1); }
  console.log(`CBSE 2026–27 CROSSWALK: PASS — ${[7, 8, 9, 10, 11, 12].reduce((n, g) => n + indiaScope('cbse', g).length, 0)} app chapters across Classes 7–12 mapped, ${omissions.length} omissions listed, no sign-off claimed`);
} else { writeFileSync(OUT, text); console.log('wrote ' + OUT); }
