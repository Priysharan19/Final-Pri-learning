#!/usr/bin/env node
// Author approvals of method-marks schemes, per question type (owner decision, 18 Nov 2026).
//   node tools/author-approvals.mjs          write client/src/engine/authorApprovals.js and server/platform/authorApproved.generated.js
//   node tools/author-approvals.mjs --check  fail when either file is out of date
//   node tools/author-approvals.mjs --gate   fail on a fixture, a sample or an automation record
// A record counts only while its digest is the type's CURRENT digest (owner-review/method-marks/types.json);
// when the scheme changes the type silently becomes not approved again. Nothing here turns method marks on.
// The server list (typeId and digest only) is generated from the same records as the client list, so the page never labels a
// table the server did not pay and the server never pays a type the page cannot label. It is the "author-approved" tier of
// Prithagoras (server/platform/schemeAward.js); it is not an examiner certification and never touches docs/marking/certifications.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const RECORDS_DIR = path.join(ROOT, 'docs/marking/author-approvals');
const TYPES = path.join(ROOT, 'owner-review/method-marks/types.json');
const OUT = path.join(ROOT, 'client/src/engine/authorApprovals.js');
const SERVER_OUT = path.join(ROOT, 'server/platform/authorApproved.generated.js');
const AUTOMATION = /\b(bot|automation|claude|agent|ci|github-actions|sample|fixture|test)\b/i;

export function readRecords(dir = RECORDS_DIR) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter(f => f.endsWith('.json') && f !== 'schema.json').sort()
    .map(f => ({ file: f, record: JSON.parse(readFileSync(path.join(dir, f), 'utf8')) }));
}

/** Problems with one record, as plain sentences. Empty means it is a well-formed record. */
export function recordProblems({ file, record }, types) {
  const out = [];
  const r = record;
  if (!r || typeof r !== 'object') return [`${file}: not an object`];
  if ('fixture' in r) out.push(`${file}: a fixture is never a record`);
  if (r.schemaVersion !== 1) out.push(`${file}: schemaVersion must be 1`);
  if (file !== `${r.typeId}.json`) out.push(`${file}: must be named after its type (${r.typeId}.json)`);
  if (!types.some(t => t.id === r.typeId)) out.push(`${file}: no such question type`);
  if (!/^[0-9a-f]{64}$/.test(String(r.digest))) out.push(`${file}: digest must be a sha256`);
  if (!['approved', 'changes-needed'].includes(r.verdict)) out.push(`${file}: verdict must be approved or changes-needed`);
  if (r.role !== 'author (tutor)') out.push(`${file}: role must be "author (tutor)" (never examiner or NESA)`);
  if (typeof r.approvedBy !== 'string' || r.approvedBy.trim().length < 2 || AUTOMATION.test(r.approvedBy)) out.push(`${file}: approvedBy must be the author's own name, not an automation identity`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(r.date))) out.push(`${file}: date must be YYYY-MM-DD`);
  if (typeof r.note !== 'string') out.push(`${file}: note must be text`);
  if (/examiner[- ]certified|nesa/i.test(`${r.note} ${r.role}`)) out.push(`${file}: records say author approval only, never examiner-certified or NESA`);
  return out;
}

/** The types the author has approved AND whose scheme is still the one he read. */
export function approvedTypes(records, types) {
  return records
    .filter(({ file, record }) => recordProblems({ file, record }, types).length === 0 && record.verdict === 'approved')
    .filter(({ record }) => types.find(t => t.id === record.typeId)?.digest === record.digest)
    .map(({ record }) => ({ typeId: record.typeId, digest: record.digest, approvedBy: record.approvedBy, date: record.date }));
}

export function render(approved) {
  return `// GENERATED by tools/author-approvals.mjs from docs/marking/author-approvals/ and owner-review/method-marks/types.json. Do not edit.
// The question types whose method-marks scheme the author (Priysharan Tripathi, tutor) has approved, each valid only for
// the digest he read. Empty until he reviews a type. Approval here never turns method marks on by itself.
export const AUTHOR_APPROVED = Object.freeze(${JSON.stringify(approved.map(a => Object.freeze(a)), null, 2)});
`;
}

/** The server copy: the type and the digest only. Empty until the author's committed records approve a type. */
export function renderServer(approved) {
  return `// GENERATED by tools/author-approvals.mjs from docs/marking/author-approvals/ and owner-review/method-marks/types.json. Do not edit.
// The question types whose method-marks scheme the author (Priysharan Tripathi, tutor) has approved, each valid only for the
// digest he read. This is the author-approved tier of the Prithagoras edition (schemeAward.js), not an examiner certification.
// Empty until his records are committed. Being listed never turns method marks on by itself: PRI_METHOD_MARKS=on is also needed.
export const AUTHOR_APPROVED_SERVER = Object.freeze(${JSON.stringify(approved.map(a => Object.freeze({ typeId: a.typeId, digest: a.digest })), null, 2)}.map(a => Object.freeze(a)));
`;
}

const types = JSON.parse(readFileSync(TYPES, 'utf8')).types;
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const records = readRecords();
  const problems = records.flatMap(r => recordProblems(r, types));
  if (process.argv.includes('--gate')) {
    if (problems.length) { console.error(problems.join('\n')); console.error('AUTHOR APPROVALS GATE: FAIL'); process.exit(1); }
    console.log(`AUTHOR APPROVALS GATE: PASS — ${records.length} record(s), none a fixture, sample or automation record`);
  } else {
    const approved = approvedTypes(records, types);
    const text = render(approved);
    const serverText = renderServer(approved);
    if (process.argv.includes('--check')) {
      const same = existsSync(OUT) && readFileSync(OUT, 'utf8') === text && existsSync(SERVER_OUT) && readFileSync(SERVER_OUT, 'utf8') === serverText;
      console.log(same ? 'AUTHOR APPROVALS: PASS — the client and server copies match the records' : 'AUTHOR APPROVALS: FAIL — run node tools/author-approvals.mjs');
      process.exit(same ? 0 : 1);
    }
    writeFileSync(OUT, text);
    writeFileSync(SERVER_OUT, serverText);
    console.log(`wrote ${path.relative(ROOT, OUT)} and ${path.relative(ROOT, SERVER_OUT)} (${approved.length} approved)`);
  }
}
