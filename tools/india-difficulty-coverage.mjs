#!/usr/bin/env node
// Pri Learning · India difficulty coverage report (issue #408)
//
// Lists, for every India chapter × track cell, which difficulty levels have an
// authored question form — for the chapter as a whole and for each dot point —
// and names the cells where the track's hardest level has none. It reads the
// same engine function the picker and the practice route use
// (indiaRequestableDifficulties), so the report cannot disagree with what a
// student is offered.
//
// It reports authored FORMS, nothing more. A form existing at a level is not a
// claim that it has been human-reviewed, that it is past-paper sourced, or that
// it reaches the depth of the exam the track is named after.
//
// Usage:
//   node tools/india-difficulty-coverage.mjs            # write the report
//   node tools/india-difficulty-coverage.mjs --check    # fail if the committed report is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SRC = new URL('../client/src/', import.meta.url).href;
const OUT = fileURLToPath(new URL('../docs/release/evidence/india-difficulty-coverage.md', import.meta.url));

const { IN_TRACKS } = await import(`${SRC}engine/curriculum-in.js`);
const { indiaScope, indiaDifficultyWindow, indiaRequestableDifficulties, indiaChapterGrade } = await import(`${SRC}engine/indiaProduct.js`);

// One profile class per track view the product shows. The JEE tracks serve the
// same Classes 11–12 scope and window to a Class 11 and a Class 12 student, so
// one row per chapter covers both.
const VIEWS = [
  ...[7, 8, 9, 10, 11, 12].map(grade => ({ track: 'cbse', grade })),
  { track: 'jee-main', grade: 12 },
  { track: 'jee-advanced', grade: 12 },
  { track: 'olympiad', grade: 9 }
];

const rows = [];
for (const { track, grade } of VIEWS) {
  const { floor, ceiling } = indiaDifficultyWindow(track, grade);
  for (const chapter of indiaScope(track, grade)) {
    const chapterLevels = indiaRequestableDifficulties(chapter, { track, grade });
    const dps = (chapter.dotpoints || []).map((text, ordinal) => ({
      ordinal, text, levels: indiaRequestableDifficulties(chapter, { track, grade, dotpoint: ordinal })
    }));
    const hardestForms = new Set((chapter.covers || []).filter(c => (c.diff || []).includes(ceiling)).map(c => `${c.gen}@${c.dp.join('+')}`)).size;
    rows.push({
      track, trackName: IN_TRACKS[track].name, grade: indiaChapterGrade(chapter), id: chapter.id, name: chapter.name,
      floor, ceiling, chapterLevels, dps, hardestForms,
      chapterHasHardest: chapterLevels.includes(ceiling),
      dpsWithoutHardest: dps.filter(d => !d.levels.includes(ceiling)),
      dpsWithNothingInWindow: dps.filter(d => !d.levels.length)
    });
  }
}

const D = list => (list.length ? list.map(d => `D${d}`).join(' ') : '—');
const byTrack = t => rows.filter(r => r.track === t);
const lines = [];
lines.push('# India difficulty coverage — where the hardest level has no authored form');
lines.push('');
lines.push('Generated by `node tools/india-difficulty-coverage.mjs` from the engine\'s own');
lines.push('`indiaRequestableDifficulties` (issue #408). Do not edit by hand; `--check` fails when it is stale.');
lines.push('');
lines.push('**What this is.** A count of authored question *forms* per chapter × track × level. A level is');
lines.push('listed only when a form is authored at exactly that level inside the track\'s difficulty window.');
lines.push('');
lines.push('**What this is not.** It is not evidence of human review, of past-paper provenance, of the number of');
lines.push('distinct reasoning archetypes at a level, or that a "D4" form reaches the depth of the examination a');
lines.push('track is named after. A cell that is not listed below has *a* form at the hardest level; it may be a');
lines.push('single routine template.');
lines.push('');
lines.push('**What the product does with a gap.** The picker does not offer a level that has no authored form for');
lines.push('the chosen chapter or dot point. A request that still names one (an old link, a typed URL, a task) is');
lines.push('refused: no question is served at another level. The page says the level is unavailable, lists the');
lines.push('levels that do exist, and serves a question only after the student chooses one.');
lines.push('');
lines.push('## Summary');
lines.push('');
lines.push('| Track | Window | Chapters | Chapters with no form at the hardest level | Dot points | Dot points with no form at the hardest level | Dot points with no form anywhere in the window |');
lines.push('|---|---|---:|---:|---:|---:|---:|');
for (const t of ['cbse', 'jee-main', 'jee-advanced', 'olympiad']) {
  const r = byTrack(t);
  const dps = r.flatMap(x => x.dps);
  lines.push(`| ${IN_TRACKS[t].name} | D${r[0].floor}–D${r[0].ceiling} | ${r.length} | ${r.filter(x => !x.chapterHasHardest).length} | ${dps.length} | ${r.reduce((n, x) => n + x.dpsWithoutHardest.length, 0)} | ${r.reduce((n, x) => n + x.dpsWithNothingInWindow.length, 0)} |`);
}
const allDps = rows.flatMap(x => x.dps);
lines.push(`| **All** | | **${rows.length}** | **${rows.filter(x => !x.chapterHasHardest).length}** | **${allDps.length}** | **${rows.reduce((n, x) => n + x.dpsWithoutHardest.length, 0)}** | **${rows.reduce((n, x) => n + x.dpsWithNothingInWindow.length, 0)}** |`);
lines.push('');
lines.push(`Chapter × track cells where the hardest level rests on a **single** authored form: ${rows.filter(x => x.hardestForms === 1).length} of ${rows.length}.`);
lines.push('');
lines.push('## Chapter × track cells with no authored form at the hardest level');
lines.push('');
const noHardest = rows.filter(r => !r.chapterHasHardest);
if (!noHardest.length) lines.push('None.');
else {
  lines.push('| Track | Class | Chapter | Hardest level | Levels that do have a form |');
  lines.push('|---|---:|---|---|---|');
  for (const r of noHardest) lines.push(`| ${r.trackName} | ${r.grade ?? '—'} | ${r.name} (\`${r.id}\`) | D${r.ceiling} | ${D(r.chapterLevels)} |`);
}
lines.push('');
lines.push('## Chapter × track cells where some dot point has no form at the hardest level');
lines.push('');
lines.push('`Forms at hardest` counts the distinct authored (generator, dot-point) forms at the hardest level for the chapter.');
lines.push('');
for (const t of ['cbse', 'jee-main', 'jee-advanced', 'olympiad']) {
  const r = byTrack(t).filter(x => x.dpsWithoutHardest.length);
  lines.push(`### ${IN_TRACKS[t].name} — ${r.length} of ${byTrack(t).length} chapters`);
  lines.push('');
  if (!r.length) { lines.push('None.'); lines.push(''); continue; }
  lines.push('| Class | Chapter | Chapter levels | Forms at hardest | Dot points without the hardest level (levels they do have) |');
  lines.push('|---:|---|---|---:|---|');
  for (const x of r) {
    const dps = x.dpsWithoutHardest.map(d => `${d.ordinal + 1}. ${d.text.replace(/\|/g, '\\|')} (${D(d.levels)})`).join('<br>');
    lines.push(`| ${x.grade ?? '—'} | ${x.name} (\`${x.id}\`) | ${D(x.chapterLevels)} | ${x.hardestForms} | ${dps} |`);
  }
  lines.push('');
}
const text = lines.join('\n') + '\n';

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error('india-difficulty-coverage: docs/release/evidence/india-difficulty-coverage.md is stale — run node tools/india-difficulty-coverage.mjs');
    process.exit(1);
  }
  console.log(`india-difficulty-coverage: up to date (${rows.length} chapter×track cells)`);
} else {
  writeFileSync(OUT, text);
  console.log(`india-difficulty-coverage: wrote ${rows.length} chapter×track cells; ${noHardest.length} without a hardest-level form; ${rows.reduce((n, x) => n + x.dpsWithoutHardest.length, 0)}/${allDps.length} dot points without one`);
}
