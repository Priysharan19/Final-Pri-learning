/** Straight line sampled with n points. */
const L = (x1, y1, x2, y2, n = 12) =>
  Array.from({ length: n }, (_, i) => [x1 + (x2 - x1) * i / (n - 1), y1 + (y2 - y1) * i / (n - 1)]);

/** Elliptical arc (degrees, clockwise screen coords). */
const A = (cx, cy, rx, ry, a0, a1, n = 16) =>
  Array.from({ length: n }, (_, i) => {
    const a = (a0 + (a1 - a0) * i / (n - 1)) * Math.PI / 180;
    return [cx + rx * Math.cos(a), cy + ry * Math.sin(a)];
  });

const join = (...parts) => parts.flat();

