// Pri Learning · English — the source catalogue.
//
// This file is the contract. Every key here must exist in every other language,
// and every `t('…')` call in the app must name a key here; client/test/
// i18n-check.mjs fails the build on either, so a string added to a screen
// without a translation cannot ship, and a key translated into Hindi but never
// used cannot pad the count.
//
// WRITING RULES, learned the hard way from the strings this replaced.
//
// 1. A sentence is one entry. The code this came from wrote
//    `{goal - done} more to hit today’s goal.` and `{n} topic{n === 1 ? '' : 's'}`.
//    Both assume English word order and English plural morphology, and both
//    are unfixable from inside the JSX. The whole sentence lives here with the
//    number as `{n}`, so Hindi can put the verb last and the postposition where
//    Hindi puts postpositions.
//
// 2. Counted nouns are `{ one, other }`, never a suffixed 's'. The forms are
//    picked by each language's own CLDR rule — see pluralCategory in
//    languages.js, and note that Hindi and English disagree about zero.
//
// 3. Placeholders are named, never positional. `{done}` and `{goal}` can swap
//    order in a translation; `%s` and `%s` cannot.
//
// 4. Nothing here is assembled from fragments at the call site. If a screen
//    needs "3 of 10 questions", that is one key with two placeholders, not a
//    "of" key between two numbers.
//
// WHAT IS DELIBERATELY NOT HERE. Question text, worked solutions, hints,
// syllabus chapter names and the marker's feedback are generated by the engine
// and the NCERT curriculum data, not by the UI. They are not chrome and a
// translation seam cannot reach them — see the note at the head of
// client/test/i18n-check.mjs for what that means for a Hindi-medium student.
