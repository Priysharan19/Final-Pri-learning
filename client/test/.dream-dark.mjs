import { chromium } from '@playwright/test';
const OUT = process.env.OUT, BASE = 'http://localhost:5173';
const b = await chromium.launch();
const page = await (await b.newContext({ viewport: { width: 1180, height: 820 } })).newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message));
await page.goto(BASE + '/');
await page.getByRole('button', { name: 'Get Started' }).click();
await page.waitForSelector('[data-onboarding-step="1"]');
await page.screenshot({ path: `${OUT}/d-onb1.png` });
await page.getByRole('button', { name: 'Student', exact: true }).click();
await page.locator('.auth-card .btn-primary').click();
await page.waitForSelector('[data-onboarding-step="2"]');
await page.locator('#signup-track').selectOption('10');
await page.screenshot({ path: `${OUT}/d-onb2.png` });
await page.locator('.auth-card .btn-primary').click();
await page.waitForSelector('[data-onboarding-step="3"]');
await page.locator('#signup-name').fill('Asha Verma');
await page.locator('.auth-card .btn-primary').click();
await page.waitForSelector('[data-onboarding-step="4"]');
await page.screenshot({ path: `${OUT}/d-onb4.png` });
await page.locator('.auth-card .btn-primary').click();
await page.waitForSelector('[data-onboarding-step="5"]');
await page.getByRole('button', { name: 'Start learning' }).click();
await page.waitForSelector('.home-greet');
await page.getByRole('button', { name: /dark theme/i }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${OUT}/d-home-dark.png` });
await page.goto(BASE + '/settings'); await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/d-settings-dark.png` });
await page.goto(BASE + '/practice'); await page.waitForSelector('.q-prompt');
await page.getByRole('button', { name: 'Show solution' }).click();
await page.waitForSelector('.eval-card'); await page.waitForTimeout(600);
await page.screenshot({ path: `${OUT}/d-practice-dark.png` });
console.log(errs.join('\n') || 'no errors');
await b.close();
