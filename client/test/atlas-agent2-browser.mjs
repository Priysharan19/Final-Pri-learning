import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const root = process.cwd().replace(/\/client$/, '');
const out = root + '/docs/prototypes';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
let checks=0;
try {
  const page = await browser.newPage({viewport: {width:1440,height:1000},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',err => errors.push(String(err)));
  await page.goto('http://127.0.0.1:4217/atlas-agent2.html',{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Knowledge Atlas'}).waitFor();
  assert.ok(await page.getByText('SYNTHETIC DEMONSTRATION').count());
  assert.ok((await page.locator('[data-graph-node]').count()) >= 15);
  assert.ok((await page.locator('.pa2-concept-list button').count()) >= 15);
  checks+=3;
  await page.screenshot({path:out+'/atlas-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Conceptual',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Conceptual',exact:true}).getAttribute('aria-pressed'),'true');
  await page.getByRole('button',{name:'Learning evidence',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Learning evidence',exact:true}).getAttribute('aria-pressed'),'true');
  checks+=2;
  await page.getByRole('button',{name:'Prerequisites',exact:true}).click();
  await page.locator('.pa2-concept-list button').first().click();
  assert.equal(await page.locator('.pa2-concept-list button').first().getAttribute('aria-current'),'true');
  checks++;
  const next = page.locator('[data-graph-node]').first();
  await next.focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('[data-graph-node]').nth(1).getAttribute('aria-pressed'),'true');
  checks++;
  await page.getByRole('button',{name:'Centre'}).click();
  await page.screenshot({path:out+'/atlas-focus-navigation.png',fullPage:true});
  await page.getByRole('button',{name:'Laboratory',exact:true}).click();
  await page.getByRole('heading',{name:'When two lines meet'}).waitFor();
  assert.equal(await page.locator('[data-result-kind]').getAttribute('data-result-kind'),'unique');
  checks++;
  for(const [button,kind] of [['Parallel','parallel'],['Coincident','coincident'],['Degenerate','inconsistent'],['Intersecting','unique']]){
    await page.getByRole('button',{name:button,exact:true}).click();
    assert.equal(await page.locator('[data-result-kind]').getAttribute('data-result-kind'),kind);
    assert.equal(await page.locator('.pa2-lab-plot circle').count(),kind==='unique'?2:0);
    checks++;
  }
  await page.getByRole('slider',{name:'Line 1 coefficient a'}).fill('0');
  assert.equal(await page.getByRole('slider',{name:'Line 1 coefficient a'}).inputValue(),'0');
  await page.getByRole('button',{name:'Reset'}).click();
  assert.equal(await page.locator('[data-result-kind]').getAttribute('data-result-kind'),'unique');
  checks+=2;
  await page.screenshot({path:out+'/laboratory-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Open practice question'}).click();
  await page.getByRole('heading',{name:'Paper transition contract'}).waitFor();
  assert.ok((await page.locator('pre').innerText()).includes('c10-pair-linear-equations'));
  checks++;
  const mobile=await browser.newPage({ viewport: {width:390,height:844},deviceScaleFactor:1 });
  mobile.on('pageerror',err => errors.push(String(err)));
  await mobile.goto('http://127.0.0.1:4217/atlas-agent2.html',{waitUntil:'networkidle'});
  assert.ok(await mobile.locator('.pa2-concept-list button').first().isVisible());
  assert.ok(!(await mobile.locator('.pa2-viewport').isVisible()));
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth > window.innerWidth),false);
  checks+=3;
  await mobile.screenshot({path:out+'/atlas-mobile.png',fullPage:true});
  await mobile.getByRole('button',{name:'Laboratory',exact:true}).click();
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth > window.innerWidth),false);
  await mobile.getByRole('button',{name:'Parallel',exact:true}).click();
  assert.equal(await mobile.locator('[data-result-kind]').getAttribute('data-result-kind'),'parallel');
  checks+=2;
  await mobile.screenshot({path:out+'/laboratory-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS PRI ATLAS Agent 2 browser: '+checks+' interactions/accessibility/responsive checks; five screenshots; no page errors');
} finally { await browser.close(); }
