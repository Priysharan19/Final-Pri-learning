// ─────────────────────────────────────────────────────────────────────────────
// Pri Learning · the served-question sample in the examiner packet (#499)
//
// One question for every chapter the India curriculum serves (its first
// cover, at the cover's lowest difficulty, seed 1), with what the server
// prints as the answer and the marker's verdict on a fixed set of writings:
// the key, the key with the box's unit, ₹ on an amount, the key written as a
// sum still to do (D13), a neighbouring wrong value, and a contradicting unit
// (D14). The examiner marks the same writings and notes every disagreement.
//
//   node client/test/support/examiner-sample.mjs           write docs/marking/examiner-sample-v1.md
//   node client/test/support/examiner-sample.mjs --check   fail if the file is stale
//
// SYNTHETIC: generated questions and the deterministic checker in-process.
// ─────────────────────────────────────────────────────────────────────────────
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const OUT = path.join(ROOT, 'docs/marking/examiner-sample-v1.md');
const { checkAnswer } = await import(path.join(ROOT, 'client/src/engine/checker.js'));
const { generateQuestion, loadAllBanks, GENERATORS } = await import(path.join(ROOT, 'client/src/engine/generators/index.js'));
const { IN_CHAPTERS } = await import(path.join(ROOT, 'client/src/engine/curriculum-in.js'));
const { answerTextFor } = await import(path.join(ROOT, 'server/platform/practice.js'));
await loadAllBanks();

const fmt = x => (Number.isInteger(x) ? String(x) : String(Number(x.toPrecision(12))));
const cell = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const verdict = (q, input) => {
  let r;
  try { r = checkAnswer(q, input); } catch { r = { correct: false, invalid: true }; }
  if (r.correct === true) return '✓ credited';
  if (r.invalid) return /Work it out first/.test(r.feedback || '') ? 'refused (D13)' : 'unread';
  return '✗ wrong';
};
const RUPEE = /₹|\bRs\b|\brupees?\b/i;

const rows = [];
for (const chapter of IN_CHAPTERS) {
  const cover = (chapter.covers || []).find(c => GENERATORS[c.gen]);
  if (!cover) continue;
  const d = Math.min(...(cover.diff || [1]));
  let q;
  try { q = generateQuestion(cover.gen, d, 1); } catch { continue; }
  if (!q || q.answerType === 'working') continue;
  const printed = String(answerTextFor(q) ?? '');
  const forms = [];
  if (q.answerType === 'numeric' && Number.isFinite(q.answer?.value)) {
    const a = q.answer, v = a.value;
    const key = a.canonicalInput || (a.simplestFraction && a.simplestFraction.d !== 1 ? `${a.simplestFraction.n}/${a.simplestFraction.d}` : fmt(v));
    forms.push(['key', key]);
    if (q.answerSuffix) forms.push(['with the box unit', `${key} ${String(q.answerSuffix).trim()}`]);
    if (RUPEE.test(String(q.answerPrefix ?? '')) || (RUPEE.test(q.prompt) && !q.answerSuffix)) forms.push(['with ₹', `₹${key}`]);
    if (Number.isInteger(v)) forms.push(['as a sum still to do', `${v - 1} + 1`]);
    forms.push(['a neighbouring value', fmt(Number.isInteger(v) ? v + 1 : v * 1.01)]);
    forms.push(['a contradicting unit', `${key} kg`]);
  } else if (q.answerType === 'mcq') {
    forms.push(['the keyed option', String(q.answer.correctIndex)]);
    forms.push(['another option', String((q.answer.correctIndex + 1) % Math.max(2, (q.mcqOptions || []).length))]);
  } else {
    forms.push(['the printed answer', printed]);
  }
  rows.push({ chapter, q, d, printed, forms: forms.map(([label, input]) => ({ label, input, verdict: verdict(q, input) })) });
}

const lines = [];
lines.push('# Examiner packet · served-question sample (V1)');
lines.push('');
lines.push('Generated by `node client/test/support/examiner-sample.mjs`; do not edit by hand. One question for every chapter the India curriculum serves: its first cover, at that cover\'s lowest difficulty, seed 1. For each, the answer the server prints after resolution and the marker\'s verdict on a fixed set of writings. **The examiner marks the same writings independently and notes every disagreement** (see `docs/release/EXAMINER-REQUEST.md`, Part A).');
lines.push('');
lines.push('Verdicts: `✓ credited` (full marks), `✗ wrong` (no marks, the try is spent), `refused (D13)` (an operation is left to do; returned unread with guidance, no try spent), `unread` (not read as an answer; no try spent). Marks are for the final answer only (D12). SYNTHETIC: generated questions and the deterministic checker; no student wrote these.');
lines.push('');
lines.push(`Chapters sampled: ${rows.length}.`);
lines.push('');
for (const { chapter, q, d, printed, forms } of rows) {
  lines.push(`## ${cell(chapter.name)} (${chapter.grade ? `Class ${chapter.grade}` : 'Olympiad'}) · \`${q.subtopic}\` D${d} seed 1`);
  lines.push('');
  lines.push(`> ${cell(q.prompt)}`);
  lines.push('');
  const box = [q.answerPrefix ? `prefix "${cell(q.answerPrefix)}"` : null, q.answerSuffix ? `unit "${cell(q.answerSuffix)}"` : null].filter(Boolean).join(', ');
  lines.push(`Answer type: ${q.answerType}${box ? ` (${box})` : ''}. Printed answer: \`${cell(printed)}\`${q.answerType === 'mcq' && Array.isArray(q.mcqOptions) ? ` (options: ${q.mcqOptions.map((o, i) => `${i}: ${cell(o)}`).join('; ')})` : ''}.`);
  lines.push('');
  lines.push('| Writing | Input | Pri\'s verdict | Examiner |');
  lines.push('|---|---|---|---|');
  for (const f of forms) lines.push(`| ${f.label} | \`${cell(f.input)}\` | ${f.verdict} | |`);
  lines.push('');
}
const text = lines.join('\n');
const digest = createHash('sha256').update(text).digest('hex');
const body = `${text}\n**Sample digest (sha256 of everything above this line):** \`${digest}\`\n`;

if (process.argv.includes('--check')) {
  const onDisk = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (onDisk !== body) {
    console.log('EXAMINER SAMPLE: FAIL — docs/marking/examiner-sample-v1.md does not match the marker; run node client/test/support/examiner-sample.mjs');
    process.exit(1);
  }
  console.log(`EXAMINER SAMPLE: PASS — ${rows.length} chapters, digest ${digest.slice(0, 12)}…`);
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${path.relative(ROOT, OUT)} — ${rows.length} chapters, digest ${digest}`);
}
