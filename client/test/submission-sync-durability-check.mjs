// ─────────────────────────────────────────────────────────────────────────────
// §22 — A practice attempt and its cloud queue entry are one write.
//
// The defect: the local backend committed the attempt, and the API layer
// queued it for cloud sync afterwards, in a second write. An app killed between
// the two left an attempt the cloud would never hear about, and the replay
// that recovered the submission (correctly) did not queue it either, so the
// gap was permanent. Now the queue entry rides in the attempt's own
// transaction; these checks pin that, with a crash injected into the
// transaction itself and with the API layer bypassed entirely.
//
// Also pinned here (review of #269):
//   · a first try of a question that was then skipped never replays as open;
//   · a replay hands back the explanation stored with the record, not one
//     regenerated by whatever engine is installed at replay time;
//   · an answered pending question is served with honest copy.
// Usage: node client/test/submission-sync-durability-check.mjs
// ─────────────────────────────────────────────────────────────────────────────
import assert from 'node:assert/strict';
import { installBrowserEnv, resetStorage } from './backend-check.mjs';

installBrowserEnv(); resetStorage();

const { api } = await import('../src/api.js');
const { dispatch } = await import('../src/local/backend.js');
const idb = await import('../src/local/idb.js');
const { checkAnswer } = await import('../src/engine/checker.js');
const { loadAllBanks } = await import('../src/engine/generators/index.js');
const { cloudLinkRowId } = await import('../src/platform/cloudAccount.js');
const { subtopicsForYear } = await import('../src/engine/curriculum.js');
await loadAllBanks();

let passed = 0;
const failures = [];
async function check(name, fn) {
  try { await fn(); passed++; }
  catch (e) { failures.push(`${name}\n      ${String(e?.message || e).split('\n').slice(0, 6).join('\n      ')}`); }
}

// ── A crash, injected into the transaction itself ───────────────────────────
// The fake IndexedDB is the one the app opened. The next read-write
// transaction that writes the cloud queue row throws on that write, the way a
// process dying mid-commit leaves nothing of the transaction behind.
const database = await new Promise((resolve, reject) => {
  const req = globalThis.indexedDB.open('pri-learning');
  req.onsuccess = () => resolve(req.result);
  req.onerror = () => reject(req.error);
});
let crashQueueWrite = false;
const realTransaction = database.transaction.bind(database);
database.transaction = (stores, mode) => {
  const tr = realTransaction(stores, mode);
  const names = Array.isArray(stores) ? stores : [stores];
  if (crashQueueWrite && mode === 'readwrite' && names.includes('device') && names.includes('attempts')) {
    crashQueueWrite = false;
    const objectStore = tr.objectStore.bind(tr);
    tr.objectStore = (name) => {
      const st = objectStore(name);
      if (name !== 'device') return st;
      return new Proxy(st, {
        get(target, prop) {
          if (prop === 'put') return () => { throw new Error('simulated crash while committing'); };
          const v = target[prop];
          return typeof v === 'function' ? v.bind(target) : v;
        }
      });
    };
  }
  return tr;
};

const YEAR10 = subtopicsForYear(10).map(t => t.id);
let turn = 0;
function canonical(q) {
  const a = q?.answer; if (!a) return null;
  if (a.canonicalInput !== undefined) return String(a.canonicalInput);
  if (q.answerType === 'numeric') return a.surdForm || a.simplestFraction || a.requireExact ? null : String(a.value);
  if (q.answerType === 'mcq') return String(a.correctIndex);
  return null;
}
function wrongFor(q) {
  if (q.answerType === 'numeric') return String((Number(q.answer.value) || 0) + 7);
  if (q.answerType === 'mcq') return String(((q.answer.correctIndex || 0) + 1) % Math.max(2, q.mcqOptions?.length || 4));
  return null;
}
async function markable() {
  for (let i = 0; i < 60; i++) {
    const s = await api.post('/practice/next', { mode: 'topic', subtopic: YEAR10[turn++ % YEAR10.length], resume: false });
    const q = (await idb.get('questions', s.question.id)).payload;
    const right = canonical(q), wrong = wrongFor(q);
    if (right !== null && wrong !== null && checkAnswer(q, right).correct && !checkAnswer(q, wrong).correct
      && !checkAnswer(q, wrong).invalid && !(q.answerType === 'mcq' && q.answer.optionTraps?.[Number(wrong)])) {
      return { id: s.question.id, right, wrong, q };
    }
    await api.post(`/practice/${s.question.id}/discard`, {});
  }
  throw new Error('no markable question was served');
}
const sid = (n) => `sub_durability_${String(n).padStart(4, '0')}`;
const attemptsOf = async (pid, qid) => (await idb.byIndex('attempts', 'pid', pid)).filter(a => a.questionId === qid);
const queued = async (pid, qid) => ((await idb.get('device', `pri-cloud-outbox-v1:${pid}`))?.items || [])
  .filter(x => x.kind === 'practice-progress' && x.entityId === qid);

const me = (await api.post('/profiles', { name: 'Durability Student', year: 10 })).user;
{
  const now = Date.now();
  await idb.put('device', { id: cloudLinkRowId(me.id), accountId: `acct-${me.id}`, role: 'student', emailVerified: true, linkedAt: now, lastVerifiedAt: now, lastSyncAt: null,
    entitlement: { plan: 'premium', status: 'active', provider: 'web', currentPeriodEnd: now + 30 * 86400000, offlineUntil: now + 7 * 86400000, issuedAt: now, sourceVersion: 1 } });
}

await check('killed after the commit, before the API layer ran: the attempt is already queued, once', async () => {
  const t = await markable();
  // The backend alone — nothing after it runs, as if the app died on return.
  const r = await dispatch('POST', `/practice/${t.id}/submit`, { answer: t.right, ms: 500, submissionId: sid(1) });
  assert.equal(r.resolved, true); assert.equal(r.syncQueued, true);
  const attempts = await attemptsOf(me.id, t.id);
  let q = await queued(me.id, t.id);
  assert.equal(attempts.length, 1);
  assert.equal(q.length, 1, 'queued in the same write as the attempt');
  assert.equal(q[0].sourceId, attempts[0].id, 'naming that exact attempt');
  // Relaunch: the card replays the submission through the full API path.
  const replay = await api.post(`/practice/${t.id}/submit`, { answer: t.right, ms: 500, submissionId: sid(1) });
  assert.equal(replay.replayed, true);
  q = await queued(me.id, t.id);
  assert.equal(q.length, 1, 'the replay does not queue it a second time');
  assert.equal((await attemptsOf(me.id, t.id)).length, 1);
});

await check('a crash inside the commit leaves neither attempt nor queue entry, and the replay lands both once', async () => {
  const t = await markable();
  const before = (await api.get('/me')).user;
  crashQueueWrite = true;
  await assert.rejects(api.post(`/practice/${t.id}/submit`, { answer: t.right, ms: 500, submissionId: sid(2) }), /simulated crash/);
  assert.equal(crashQueueWrite, false, 'the crash was injected into the attempt transaction');
  assert.equal((await attemptsOf(me.id, t.id)).length, 0, 'no attempt without its queue entry');
  assert.equal((await queued(me.id, t.id)).length, 0, 'no queue entry without its attempt');
  const row = await idb.get('questions', t.id);
  assert.ok(!row.answered, 'the question is still open');
  assert.equal((await api.get('/me')).user.xp, before.xp, 'no XP from a rolled-back commit');
  const replay = await api.post(`/practice/${t.id}/submit`, { answer: t.right, ms: 500, submissionId: sid(2) });
  assert.equal(replay.resolved, true); assert.equal(replay.replayed, undefined, 'marked now, the first delivery never landed');
  const attempts = await attemptsOf(me.id, t.id);
  const q = await queued(me.id, t.id);
  assert.equal(attempts.length, 1); assert.equal(q.length, 1); assert.equal(q[0].sourceId, attempts[0].id);
});

await check('a reveal is queued in its own transaction too', async () => {
  const t = await markable();
  const r = await dispatch('POST', `/practice/${t.id}/reveal`, { ms: 100 });
  assert.equal(r.syncQueued, true);
  const attempts = await attemptsOf(me.id, t.id);
  const q = await queued(me.id, t.id);
  assert.equal(q.length, 1); assert.equal(q[0].sourceId, attempts[0].id);
});

await check('a first try on a question that was then skipped never replays as still open', async () => {
  const t = await markable();
  const first = await api.post(`/practice/${t.id}/submit`, { answer: t.wrong, submissionId: sid(3) });
  assert.equal(first.resolved, false);
  await api.post(`/practice/${t.id}/discard`, {});
  const e = await api.post(`/practice/${t.id}/submit`, { answer: t.wrong, submissionId: sid(3) }).then(() => null, err => err);
  assert.ok(e, 'the replay is refused');
  assert.equal(e.status, 409); assert.equal(e.code, 'QUESTION_DISCARDED');
});

await check('a replay returns the explanation stored with the record, not a regenerated one', async () => {
  const t = await markable();
  const live = await api.post(`/practice/${t.id}/submit`, { answer: t.wrong, submissionId: sid(4) });
  // Stand in for "the engine changed between delivery and replay": rewrite the
  // stored explanation and the authored question text the engine would use.
  const row = await idb.get('questions', t.id);
  assert.equal(row.lastTry?.replay?.feedback, live.feedback, 'the first try stored what it said');
  await idb.put('questions', { ...row, lastTry: { ...row.lastTry, replay: { ...row.lastTry.replay, feedback: 'stored-try-explanation' } } });
  const tryReplay = await api.post(`/practice/${t.id}/submit`, { answer: t.wrong, submissionId: sid(4) });
  assert.equal(tryReplay.feedback, 'stored-try-explanation');

  const done = await api.post(`/practice/${t.id}/submit`, { answer: t.wrong, submissionId: sid(5) });
  assert.equal(done.resolved, true);
  const resolved = await idb.get('questions', t.id);
  assert.equal(resolved.resolution.replay?.feedback ?? null, done.feedback ?? null);
  assert.deepEqual(resolved.resolution.replay?.stepReport ?? null, done.stepReport ?? null);
  await idb.put('questions', { ...resolved, resolution: { ...resolved.resolution, replay: { ...resolved.resolution.replay, feedback: 'stored-resolution-explanation' } } });
  const replay = await api.post(`/practice/${t.id}/submit`, { answer: t.wrong, submissionId: sid(5) });
  assert.equal(replay.replayed, true);
  assert.equal(replay.feedback, 'stored-resolution-explanation');
  assert.equal(replay.correct, false);
});

await check('an answered pending question is served as a result to see, not a question to answer', async () => {
  const t = await markable();
  await api.post(`/practice/${t.id}/submit`, { answer: t.right, submissionId: sid(6) });
  const relaunch = await api.post('/practice/next', { resume: true, pendingQuestionId: t.id });
  assert.equal(relaunch.question.id, t.id);
  assert.match(relaunch.why, /result of the answer you submitted/);
  const open = await markable();
  const resumed = await api.post('/practice/next', { resume: true, pendingQuestionId: open.id });
  assert.equal(resumed.why, 'Continuing your unfinished question.');
});

if (failures.length) {
  console.log(`\n✖ submission sync durability — ${failures.length} failed, ${passed} passed\n`);
  for (const f of failures) console.log('  ' + f + '\n');
  process.exit(1);
}
console.log(`PASS — §22 submission sync durability: ${passed} groups (attempt and cloud queue entry are one write, crash-injected; skipped tries stay skipped; replays return stored explanations).`);
