import { chromium } from '@playwright/test';
const BASE = 'http://localhost:5173';
const b = await chromium.launch();
const page = await (await b.newContext({ viewport: { width: 1180, height: 820 } })).newPage();
await page.goto(BASE + '/');
await page.getByRole('button', { name: 'Get Started' }).click();
await page.getByRole('button', { name: 'Student', exact: true }).click();
await page.locator('.auth-card .btn-primary').click();
await page.locator('#signup-track').selectOption('10');
await page.locator('.auth-card .btn-primary').click();
await page.locator('#signup-name').fill('Reload Test');
await page.locator('.auth-card .btn-primary').click();
await page.locator('.auth-card .btn-primary').click();
await page.getByRole('button', { name: 'Start learning' }).click();
await page.waitForSelector('.home-greet');
await page.goto(BASE + '/practice?subtopic=c10-quadratic-equations');
await page.waitForSelector('.q-prompt');
for (let i = 0; i < 10 && await page.locator('.mcq').count(); i++) {
  const before = await page.locator('.q-prompt').innerText();
  await page.locator('.ctx-next').click();
  await page.waitForFunction(x => document.querySelector('.q-prompt')?.innerText !== x, before);
}
const prompt = await page.locator('.q-prompt').innerText();
await page.locator('.mode-tab', { hasText: 'Write' }).click();
await page.waitForSelector('.ink-canvas-live');
const box = await page.locator('.ink-canvas-live').boundingBox();
await page.mouse.move(box.x + 70, box.y + 60); await page.mouse.down();
for (const x of [100, 130, 160, 190]) await page.mouse.move(box.x + x, box.y + 60 + (x % 20), { steps: 5 });
await page.mouse.up();
await page.waitForSelector('.status-line[data-state="saved"]', { timeout: 8000 });
const status = await page.locator('.status-line').innerText();
const ink = () => page.evaluate(() => { const c = document.querySelector('.ink-canvas-base'); const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; let n = 0; for (let i = 3; i < d.length; i += 4) if (d[i] > 0) n++; return n; });
const before = await ink();
await page.reload();
await page.waitForSelector('.q-prompt');
const samePrompt = (await page.locator('.q-prompt').innerText()) === prompt;
await page.waitForSelector('.ink-canvas-base');
await page.waitForTimeout(800);
const after = await ink();
console.log(JSON.stringify({ status, samePrompt, inkPixelsBefore: before, inkPixelsAfterReload: after, restoredStatus: await page.locator('.status-line').innerText() }));
await page.screenshot({ path: process.env.OUT + '/reload-restored.png' });
await b.close();
