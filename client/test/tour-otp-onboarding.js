// Pri Learning · E2E flow — email, code, age, class, guardian email approval,
// synced profile, then Home and a working question.
//
// Nothing is mocked on the server side. Every /v1 request the browser makes is
// forwarded to the real platform server (server/app.js, in this process, on an
// in-memory SQLite database) with the SMS and email TEST adapters
// (PRI_SMS_PROVIDER=test, PRI_AUTH_EMAIL_PROVIDER=test), which send nothing and
// keep each code in memory. The test reads the code the way a phone would
// receive it and types it into the shipped UI.

import { pathToFileURL } from 'node:url';

const SERVER_ORIGIN_SEEN = 'http://localhost:5173';

async function startPlatform() {
  process.env.PRI_AUTH_DELIVERY_KEY = process.env.PRI_AUTH_DELIVERY_KEY || '33'.repeat(32);
  process.env.PRI_SMS_PROVIDER = 'test';
  process.env.PRI_AUTH_EMAIL_PROVIDER = 'test';
  process.env.PRI_PUBLIC_ORIGIN = SERVER_ORIGIN_SEEN;
  const { startApp } = await import('../../server/test/support/app-harness.mjs');
  const sms = await import('../../server/platform/smsProvider.js');
  return { h: await startApp(), sms };
}

export const flow = {
  id: 'otp-onboarding',
  name: 'Account · email first, child guardian approval, synced Home and working',

  async run({ page, ctx, base, check, goto, shot }) {
    const { h, sms } = await startPlatform();
    try {
      await page.addInitScript(origin => { window.__PRI_CLOUD_ORIGIN__ = origin; }, base);
      const seen = [];
      const proxy = async route => {
        const request = route.request();
        const url = new URL(request.url());
        seen.push(`${request.method()} ${url.pathname}`);
        const incoming = request.headers();
        const headers = { Accept: 'application/json', Origin: SERVER_ORIGIN_SEEN };
        for (const name of ['cookie', 'content-type', 'x-pri-csrf', 'x-pri-client', 'x-pri-request-id', 'idempotency-key']) {
          if (incoming[name]) headers[name] = incoming[name];
        }
        const response = await fetch(`${h.origin}${url.pathname}${url.search}`, {
          method: request.method(), headers, body: ['GET', 'HEAD'].includes(request.method()) ? undefined : request.postData() ?? undefined
        });
        const outHeaders = { 'content-type': response.headers.get('content-type') || 'application/json' };
        const cookies = typeof response.headers.getSetCookie === 'function' ? response.headers.getSetCookie() : [];
        if (cookies.length) outHeaders['set-cookie'] = cookies.join('\n');
        const retry = response.headers.get('retry-after');
        if (retry) outHeaders['retry-after'] = retry;
        return route.fulfill({ status: response.status, headers: outHeaders, body: Buffer.from(await response.arrayBuffer()) });
      };
      await ctx.route('**/v1/**', proxy);

      await goto('/');
      await page.getByRole('button', { name: 'Create your account' }).click();
      await page.waitForSelector('[data-signup-step="method"]', { timeout: 15000 });
      await check('the new signup starts by asking for an email, not a role or local profile',
        await page.getByTestId('signup-channel-email').getAttribute('aria-checked') === 'true' &&
        await page.locator('#signup-destination').getAttribute('type') === 'email');
      await check('the step heading takes focus for screen readers',
        await page.evaluate(() => document.activeElement?.id === 'signup-step-title'));
      const animation = await page.locator('.signup-step').evaluate(el => getComputedStyle(el).animationName);
      await check('reduced motion removes the step animation', animation === 'none', animation);
      await page.locator('#signup-destination').fill('asha.onboarding@example.com');
      await shot('method');
      await page.getByTestId('signup-send-code').click();
      await page.waitForSelector('[data-signup-step="code"]');
      const sent = sms.readTestOutbox({ to: 'asha.onboarding@example.com', channel: 'email' }).at(-1);
      await check('a 6-digit email code was generated by the live test backend', /^\d{6}$/.test(sent?.code || ''), JSON.stringify(sent));
      await check('the first box asks for one-time-code autofill',
        await page.locator('#signup-code-0').getAttribute('autocomplete') === 'one-time-code');
      await check('resend waits out its cooldown', await page.getByTestId('signup-resend').isDisabled());
      const wrong = sent.code === '000000' ? '111111' : '000000';
      await page.locator('#signup-code-0').focus();
      await page.keyboard.type(wrong);
      await page.getByRole('alert').waitFor({ timeout: 10000 });
      await check('wrong OTP is refused without creating a profile',
        await page.locator('[data-testid="signup-code-box"]').evaluateAll(els => els.map(e => e.value).join('')) === '' &&
        h.db.prepare("SELECT count(*) AS n FROM accounts WHERE email='asha.onboarding@example.com'").get().n === 0);
      await page.locator('#signup-code-0').focus();
      await page.keyboard.type(sent.code);
      await page.waitForSelector('[data-signup-step="age"]', { timeout: 15000 });
      await check('age is asked only after verifying the email', await page.getByTestId('signup-age-18').isVisible());
      await page.getByTestId('signup-age-15').click();
      await page.waitForSelector('[data-signup-step="class"]');
      await page.getByTestId('signup-class-9').click();
      await check('JEE is not offered below Class 11', await page.getByTestId('signup-track-jee-main').isDisabled());
      await page.getByTestId('signup-class-11').click();
      await page.getByTestId('signup-track-jee-main').click();
      await page.locator('#signup-flow-name').fill('Asha');
      await shot('class');
      await page.getByTestId('signup-class-next').click();
      await page.waitForSelector('[data-signup-step="parent"]', { timeout: 15000 });
      await check('a 15-year-old must obtain approval before Home', await page.getByRole('heading', { name: 'Now, a parent’s approval' }).isVisible());
      await check('the app shell remains inaccessible before approval', await page.locator('.shell').count() === 0);

      const account = h.db.prepare("SELECT a.id, a.email FROM accounts a WHERE a.email='asha.onboarding@example.com'").get();
      await check('the account is tied to the verified email, not an anonymous local profile', !!account && account.email === 'asha.onboarding@example.com');
      const pending = h.db.prepare('SELECT method, confirmed_at FROM guardian_consents WHERE account_id=?').get(account.id);
      await check('and it starts limited: consent pending', pending && pending.confirmed_at === null, JSON.stringify(pending));

      await page.locator('#signup-parent-name').fill('Meera');
      await page.locator('#signup-parent-destination').fill('meera.guardian@example.com');
      await page.getByTestId('signup-parent-send').click();
      await page.waitForSelector('[data-signup-step="parent-wait"]');
      await check('the child’s screen only waits for the parent: no code box, no approve button',
        await page.locator('[data-testid="signup-parent-waiting"]').isVisible() &&
          await page.locator('input[autocomplete="one-time-code"]').count() === 0 &&
          await page.getByRole('button', { name: 'Approve' }).count() === 0);
      await check('and can ask for the code again once the cooldown ends', await page.getByTestId('signup-parent-resend').isDisabled());
      const parentSms = sms.readTestOutbox({ to: 'meera.guardian@example.com', channel: 'email' }).at(-1);
      await check('the parent’s email got its consent code and independent approval page',
        parentSms?.purpose === 'guardian-consent' && /^\d{6}$/.test(parentSms.code) && parentSms.body.includes('/guardian/consent'));

      // The parent, on their own device: a separate browser context, no profile,
      // no session, nothing shared with the child's browser.
      const parentCtx = await ctx.browser().newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
      try {
        await parentCtx.addInitScript(origin => { window.__PRI_CLOUD_ORIGIN__ = origin; }, base);
        await parentCtx.route('**/v1/**', proxy);
        const parentPage = await parentCtx.newPage();
        await parentPage.goto(`${base}/guardian/consent`, { waitUntil: 'domcontentloaded' });
        await parentPage.getByRole('heading', { name: 'What you are agreeing to' }).waitFor({ timeout: 20000 });
        await check('the parent page shows the notice before the code can be entered',
          await parentPage.locator('#guardian-code-0').isDisabled());
        await parentPage.getByRole('radio', { name: 'Email' }).click();
        await parentPage.locator('#guardian-destination').fill('meera.guardian@example.com');
        await parentPage.getByTestId('guardian-agree').check();
        await parentPage.locator('#guardian-code-0').focus();
        await parentPage.evaluate(code => {
          const data = new DataTransfer(); data.setData('text', code);
          document.activeElement.dispatchEvent(new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true }));
        }, parentSms.code);
        await check('pasting fills all six boxes',
          (await parentPage.locator('[data-testid="guardian-code-box"]').evaluateAll(els => els.map(e => e.value).join(''))) === parentSms.code);
        await shot('parent-wait');
        await parentPage.getByTestId('guardian-approve').click();
        await parentPage.getByText('Asha’s account is approved', { exact: false }).waitFor({ timeout: 15000 });
        await check('the parent is told whose account they approved', true);
        await check('the parent page never held a child session',
          !(await parentCtx.cookies()).some(cookie => /session/i.test(cookie.name)));
      } finally {
        await parentCtx.close();
      }

      // The child cannot enter until activation and sync finish.
      await page.waitForSelector('.shell', { timeout: 30000 });
      await page.waitForSelector('.home-greet', { timeout: 30000 });
      await check('the learner enters Home only after guardian approval and initial sync',
        new URL(page.url()).pathname === '/' && await page.locator('[data-testid="account-activation-gate"]').count() === 0);
      await page.goto(`${base}/practice`, { waitUntil: 'domcontentloaded' });
      await page.waitForSelector('.shell', { timeout: 30000 });
      await page.waitForSelector('.q-prompt', { timeout: 30000 });

      const cloudMeStatus = await page.evaluate(async () => (await fetch('/v1/account/me', { credentials: 'include' })).status);
      await check('the same onboarding leaves a live Pri cloud session', cloudMeStatus === 200, String(cloudMeStatus));

      // The adaptive first question may legitimately be MCQ. Move to the first
      // written-answer question before checking the working modes; this keeps the
      // auth regression deterministic instead of depending on question type.
      let answerModesAvailable = false;
      for (let i = 0; i < 12; i++) {
        const photo = await page.getByRole('button', { name: 'Photo' }).count();
        const write = await page.getByRole('button', { name: 'Write' }).count();
        if (photo && write) { answerModesAvailable = true; break; }
        const next = page.locator('.ctx-next');
        if (!await next.count()) break;
        await next.click();
        await page.waitForSelector('.q-prompt', { timeout: 15000 });
        await page.waitForTimeout(80);
      }
      await check('the signed-in journey reaches a written-answer question', answerModesAvailable);
      if (answerModesAvailable) {
        await page.getByRole('button', { name: 'Photo' }).click();
        await page.waitForTimeout(120);
        await check('photo mode does not ask the newly signed-in learner to sign in again',
          await page.getByText('Sign in to read photos of your working.', { exact: false }).count() === 0);

        await page.getByRole('button', { name: 'Write' }).click();
        await page.waitForTimeout(120);
        await check('handwriting mode does not ask the newly signed-in learner to sign in again',
          await page.getByText('Reading your handwriting needs a Pri account.', { exact: false }).count() === 0);
      }

      // A normal page refresh must keep the same account linked: no return
      // to Settings and no second OTP/guardian process.
      await page.reload({ waitUntil: 'domcontentloaded' });
      await page.waitForSelector('.shell', { timeout: 30000 });
      await check('approved minor reopens Practice without a second sign-in',
        new URL(page.url()).pathname === '/practice' &&
        await page.locator('[data-testid="account-activation-gate"]').count() === 0);
      await check('minor session survives refresh with authoritative cloud identity',
        await page.evaluate(async () => (await fetch('/v1/account/me', { credentials: 'include' })).status) === 200);

      const given = h.db.prepare('SELECT method, confirmed_at FROM guardian_consents WHERE account_id=?').get(account.id);
      await check('guardian email approval is recorded on the server', given.method === 'guardian-email-otp' && given.confirmed_at > 0, JSON.stringify(given));
      await check('every step went through the real server', seen.includes('POST /v1/account/otp/verify') && seen.includes('POST /v1/account/otp/guardian/approve'));

      // Independently prove the 18+ branch on a fresh browser/account. There
      // must be no guardian row, pending screen or second sign-in prompt.
      const adultCtx = await ctx.browser().newContext({ viewport: { width: 1080, height: 820 }, reducedMotion: 'reduce' });
      try {
        await adultCtx.addInitScript(origin => { window.__PRI_CLOUD_ORIGIN__ = origin; }, base);
        await adultCtx.route('**/v1/**', proxy);
        const adult = await adultCtx.newPage();
        await adult.goto(base, { waitUntil: 'domcontentloaded' });
        await adult.getByTestId('hero-create-account').click();
        await adult.waitForSelector('[data-signup-step="method"]');
        await adult.locator('#signup-destination').fill('adult.onboarding@example.com');
        await adult.getByTestId('signup-send-code').click();
        await adult.waitForSelector('[data-signup-step="code"]');
        const adultOtp = sms.readTestOutbox({ to: 'adult.onboarding@example.com', channel: 'email' }).at(-1);
        await check('an independent adult email got its verification code', /^\d{6}$/.test(adultOtp?.code || ''));
        await adult.locator('#signup-code-0').focus();
        await adult.keyboard.type(adultOtp.code);
        await adult.waitForSelector('[data-signup-step="age"]');
        await adult.getByTestId('signup-age-18').click();
        await adult.waitForSelector('[data-signup-step="class"]');
        await adult.getByTestId('signup-class-12').click();
        await adult.locator('#signup-flow-name').fill('Adult learner');
        await adult.getByTestId('signup-class-next').click();
        await adult.waitForSelector('.home-greet', { timeout: 30000 });
        await check('18+ learner goes straight to Home, with no parent step',
          await adult.locator('[data-signup-step="parent"],[data-signup-step="parent-wait"],[data-testid="activation-guardian"]').count() === 0 &&
          await adult.locator('.shell').isVisible());
        const adultAccount = h.db.prepare("SELECT id,age_basis FROM accounts WHERE email='adult.onboarding@example.com'").get();
        const adultGuardianRows = adultAccount
          ? h.db.prepare('SELECT count(*) AS n FROM guardian_consents WHERE account_id=?').get(adultAccount.id).n : -1;
        await check('backend persists adult age authority and NO guardian consent requirement',
          adultAccount?.age_basis === 'adult' && adultGuardianRows === 0,
          JSON.stringify({ adultAccount, adultGuardianRows }));
        const adultState = await adult.evaluate(async () => {
          const r = await fetch('/v1/account/guardian/state', { credentials: 'include' });
          return r.ok ? r.json() : { status: r.status };
        });
        await check('server explicitly returns no parental confirmation for adult',
          adultState?.required === false && adultState?.state === 'not-required', JSON.stringify(adultState));
        await check('adult first sync has completed before entering the shell',
          await adult.locator('[data-testid="account-activation-gate"]').count() === 0);

        // A same-account verification refresh can happen from inside Practice;
        // it must never unmount the route or discard a photo/ink draft.
        const linkId = await adult.evaluate(accountId => new Promise(resolve => {
          const open = indexedDB.open('pri-learning');
          open.onerror = () => resolve(null);
          open.onsuccess = () => {
            const db = open.result;
            const request = db.transaction('device').objectStore('device').getAll();
            request.onsuccess = () => {
              db.close();
              const link = request.result.find(row =>
                row.id?.startsWith('pri-cloud-account-link-v1:') && String(row.accountId) === String(accountId));
              resolve(link?.id?.slice('pri-cloud-account-link-v1:'.length) || null);
            };
            request.onerror = () => { db.close(); resolve(null); };
          };
        }), adultAccount.id);
        await check('real browser has the newly linked local profile', !!linkId);
        await adult.evaluate(({ accountId, profileId }) => {
          window.__activationShellNode = document.querySelector('.shell');
          window.dispatchEvent(new CustomEvent('pri:cloud-session-change', {
            detail: { connected: true, accountId: String(accountId), localProfileId: profileId }
          }));
        }, { accountId: adultAccount.id, profileId: linkId });
        await adult.waitForTimeout(300);
        await check('same-account session refresh preserves mounted work and stays in Home',
          await adult.evaluate(() => document.querySelector('.shell') === window.__activationShellNode) &&
          await adult.locator('[data-testid="account-activation-gate"]').count() === 0);

        // A temporary 503 while rechecking consent is not an authority
        // revocation. Keep the working page mounted and retry when online.
        await adult.route('**/v1/account/guardian/state', route => route.fulfill({
          status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'temporary-outage' })
        }));
        await adult.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
        await adult.waitForTimeout(550);
        await check('temporary guardian-service outage never destroys the active shell',
          await adult.evaluate(() => document.querySelector('.shell') === window.__activationShellNode) &&
          await adult.locator('[data-testid="account-activation-gate"]').count() === 0);
        await adult.unroute('**/v1/account/guardian/state');
        await adult.evaluate(() => { delete window.__activationShellNode; });
        await adult.reload({ waitUntil: 'domcontentloaded' });
        await adult.waitForSelector('.home-greet', { timeout: 30000 });
        await check('18+ returns to Home after refresh without verification or guardian prompts',
          await adult.locator('.shell').isVisible() &&
          await adult.locator('[data-testid="account-activation-gate"]').count() === 0 &&
          await adult.locator('[data-signup-step="code"],[data-testid="activation-guardian"]').count() === 0);
        await adult.goto(`${base}/settings`, { waitUntil: 'domcontentloaded' });
        await adult.getByRole('button', { name: 'Disconnect', exact: true }).click();
        await adult.waitForSelector('[data-testid="account-activation-gate"]', { timeout: 15000 });
        await check('cloud account disconnect immediately relocks the entire main app',
          await adult.locator('.shell').count() === 0 &&
          await adult.locator('[data-testid="account-activation-gate"]').isVisible());
        await adult.goto(`${base}/practice`, { waitUntil: 'domcontentloaded' });
        await adult.waitForSelector('[data-testid="account-activation-gate"]', { timeout: 15000 });
        await check('deep-linking to Practice after logout cannot bypass account activation',
          await adult.locator('.shell').count() === 0);


      } finally { await adultCtx.close(); }
    } finally {
      await h.close();
    }
  }
};

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const { runOne } = await import('./e2e.mjs');
  process.exit(await runOne(flow) ? 1 : 0);
}
